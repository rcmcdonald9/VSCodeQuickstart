"""Shoulder-pitch gravity balancer: zero-free-length spring via cable (Anglepoise / Herder / French & Widden principle).

Geometry: pulley A sits on the torso a metres *above* the pitch axis O. Anchor B is a pin on the pitch joint's
big pulley, b metres from O along the arm (below O when the arm hangs). A cable runs B → over A → down into the
torso to a caged spring (A9: through a 2:1 tackle into a die spring). The cage is designed so the spring is at its free length when the cable length
A–B would be zero, so the spring force is k·|AB| ("zero free length").
Then the torque about O is k·a·b·sin(pitch) exactly, for any pitch: the same law the workspace study assumed.
K is adjusted by sliding pulley A along a slot (a changes), never by pre-tension (which would break the law).
"""
from __future__ import annotations

import math

import numpy as np

from .params import BASELINE, Design

A_NOM, A_RANGE = 0.050, (0.045, 0.065)   # m, pulley A height above O (slot). |a-b| ≥ 15 mm so pin B clears pulley A at pitch 180°
B = 0.030                                # m, anchor pin radius on the balancer lever (loop 7 CAD: 40 → 30 so B clears A when the arm points up)
R_PULLEY = 0.0055                        # m, pulley A radius: U604ZZ grooved bearing pulley (A9: was an ungrooved Ø12 printed pulley)
CABLE_BREAK_N = 2000.0                   # 2 mm Dyneema/UHMWPE braid (ESTIMATE; typical 150–250 daN)
SPRING_SAFE_STROKE = 0.105               # m, cage stroke available (kept for the score signature)
# A9 (loop 40, external review finding 10): the loop-7 spring could not exist. Zero free length makes the spring deflect by
# the whole A–B span (up to a + b = 80 mm) at k = 3 N/mm: it stores ≈ 11 J, and a Ø25 compression spring that does that
# without overstress is ≈ 210 mm long (25-coil, d 3.2 mm) — it never fitted the 135 mm cage. Fix: a 2:1 tackle (the cable
# runs B → A → a moving pulley on the spring plate → anchored), so the spring sees half the travel at four times the rate,
# and a stock ISO 10243 die spring (rectangular wire, high energy density) fits the cage.
TACKLE = 2
CAGE_L = 0.135
DIE = dict(name="ISO 10243 light-load (green) die spring, Ø25 hole / Ø12.5 rod, L0 115 mm (ESTIMATE rate ≈ 12 N/mm; pick the catalogue rate ≥ 4·k)",
           L0=0.115, max_frac=0.40)        # long-life deflection limit for light-load die springs (≈ 40 % of L0, ESTIMATE)


def spring_rate(K: float, a: float = A_NOM, b: float = B) -> float:
    return K / (a * b)


def torque(theta: float, k: float, a: float, b: float, rp: float = R_PULLEY) -> float:
    """Exact spring torque about O (N·m) with a finite pulley at A. theta = pitch from hanging (rad)."""
    Bp = np.array([b * math.sin(theta), -b * math.cos(theta)])          # anchor (x forward, z up)
    Ap = np.array([0.0, a])
    d = Ap - Bp
    L = float(np.linalg.norm(d))
    # tangent point on pulley A: the cable leaves B toward the pulley's near side; length to tangency
    l_t = math.sqrt(max(L * L - rp * rp, 1e-12))
    ang = math.atan2(d[1], d[0]) + math.asin(rp / L) * (1 if Bp[0] >= 0 else -1)
    u = np.array([math.cos(ang), math.sin(ang)])
    ext = l_t + rp * (math.pi / 2)          # wrap ≈ quarter turn into the torso (constant part folded into the cage)
    F = k * (ext - rp * math.pi / 2)        # cage zeroed so F = k·(free span length)
    return float(Bp[0] * F * u[1] - Bp[1] * F * u[0]), F, l_t


def study(d: Design = BASELINE):
    K = d.arm.spring_k_nm
    k = spring_rate(K)
    th = np.radians(np.linspace(-200, 60, 261))
    ideal = K * np.sin(th)
    real = np.array([torque(t, k, A_NOM, B)[0] for t in th])
    F = np.array([torque(t, k, A_NOM, B)[1] for t in th])
    span = np.array([torque(t, k, A_NOM, B)[2] for t in th])
    err = np.max(np.abs(real - ideal))
    adj = (k * A_RANGE[0] * B, k * A_RANGE[1] * B)
    ks = TACKLE ** 2 * k                                   # spring rate behind the tackle
    defl = float(span.max()) / TACKLE                      # spring deflection from free length (zero-free-length datum)
    ok = defl <= DIE["max_frac"] * DIE["L0"] and DIE["L0"] + 0.012 <= CAGE_L
    return dict(K=K, k=k, err=err, Fmax=float(F.max()), stroke=float(span.max() - span.min()), span_max=float(span.max()),
                adj=adj, cable_sf=CABLE_BREAK_N / F.max(), ks=ks, defl=defl, Fs=TACKLE * float(F.max()), energy=0.5 * k * float(span.max()) ** 2, fits=ok)


def report(d: Design = BASELINE) -> str:
    s = study(d)
    return "\n".join([
        "# Shoulder balancer (auto-generated by `python -m rnd.run_all`)", "",
        "Zero-free-length cable-spring balancer. Pulley A sits 45–65 mm above the pitch axis in a slot; pin B sits on a lever on the pitch "
        "shaft 30 mm from the axis. A cable runs B → A → (2:1 tackle) → a caged die spring in the torso, giving "
        "τ = k·a·b·sin(pitch) at every angle. Precedent: the Anglepoise lamp, Herder's spring balancers, French & Widden cable balancers.", "",
        "| Quantity | Value |", "|---|---|",
        f"| Design K (params) | {s['K']:.1f} N·m |",
        f"| Spring rate k = K/(a·b) | **{s['k'] / 1000:.2f} N/mm** |",
        f"| Max spring force (arm hanging) | {s['Fmax']:.0f} N |",
        f"| Cable span A–B, max (= zero-free-length spring travel without a tackle) | {s['span_max'] * 1000:.0f} mm; energy {s['energy']:.1f} J |",
        f"| **A9: 2:1 tackle → spring rate / deflection / force** | **{s['ks'] / 1000:.0f} N/mm / {s['defl'] * 1000:.0f} mm / {s['Fs']:.0f} N** |",
        f"| Die spring L0 {DIE['L0'] * 1000:.0f} mm: deflection {s['defl'] / DIE['L0']:.0%} of L0 (limit {DIE['max_frac']:.0%}); cage {CAGE_L * 1000:.0f} mm | {'✅' if s['fits'] else '❌'} |",
        f"| Law error from the Ø{2 * R_PULLEY * 1000:.0f} mm pulley (max over −200…60°) | {s['err']:.2f} N·m ({s['err'] / s['K']:.0%} of K) |",
        f"| K adjustment by sliding A ({A_RANGE[0] * 1000:.0f}–{A_RANGE[1] * 1000:.0f} mm) | {s['adj'][0]:.1f}–{s['adj'][1]:.1f} N·m |",
        f"| Cable safety (2 mm UHMWPE, ESTIMATE {CABLE_BREAK_N:.0f} N) | {s['cable_sf']:.0f}× |", "",
        f"**Spring (A9, loop 40):** {DIE['name']}. The loop-7 compression spring (3 N/mm over 85 mm, ≈ 11 J) would have been ≈ 210 mm long and never fitted the "
        "135 mm cage (external review finding 10). The moving pulley halves the travel; die springs store the energy in about half the length. "
        "Cable: B → U604 pulley A → U604 moving pulley on the spring plate → anchor screw on the cage.",
        "**Detach hazard (A9):** with the arm off, the spring torque K·sin(pitch) is unopposed. Detach and attach only with the arm hanging (pitch 0, "
        "where the torque is zero), with the **park pin** in: a Ø6 pin through the bracket wall into a hole in the balancer disc at pitch 0. The pitch motor holds the "
        "shaft as well while powered.",
        "**Failure mode:** with the cable cut, the arm is simply unbalanced; the pitch motor still holds it (see the workspace margins without the spring in spring.md)."])


def score(d: Design = BASELINE):
    s = study(d)
    return s["err"] / s["K"], s["fits"]


if __name__ == "__main__":
    print(report())
