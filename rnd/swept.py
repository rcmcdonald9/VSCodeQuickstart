"""Swept spacing over joint ranges (R15 extension, loop 40).  python -m rnd.swept

The static spacing check (rnd/spacing.py) sees one pose. This one rotates the moving side of a joint through its whole
range and reports the minimum gap to the static side at every step (BRepExtrema), so a part that only collides at
roll 75° or yaw 150° shows up.

Sweeps:
- **shoulder roll** −15…100° (twin.JR): moving = everything on the roll output (roll shaft + 80T, spring hub, clevis and
  yaw block, yaw cartridge, yaw shaft, upper bone top); static = roll link, roll cartridge, shoulder cap, ferrule.
- **upper-arm yaw** ±155° (the hard stops): moving = yaw shaft + 40T + upper bone / elbow housing top; static = yaw block,
  yaw cartridge and band, spring ring. Checks the stop pin hits only its slot ends.

Target: moving ≥ 2 mm (hard 1 mm), as in R15; pairs R15 classes as running (bearing-set gaps) use ≥ 0.3 mm.
"""
from __future__ import annotations

import json
from pathlib import Path

from build123d import Axis, Pos, Rot

DOCS = Path(__file__).resolve().parent.parent / "docs" / "rnd"
TARGET, HARD = 2.0, 1.0


def _sets():
    from .parts import arm, roll
    mod = roll.module()
    up = [(f"arm_{n}", Pos(0, roll.ROLL_Y, -roll.YAW_DROP) * p) for n, p, _ in arm.assembly()
          if n in ("upper_bone", "bone_cap", "cf_neck")]
    roll_out = {"roll_shaft", "roll_pulley72", "roll_spring_hub", "yaw_block", "yaw_shaft", "yaw_flange", "yaw_spring_ring", "yaw_plate_bot",
                "yaw_band", "yaw_stop_pin"}
    moving_roll = [(n, p) for n, p, _ in mod if n in roll_out or n.startswith("yaw_")] + up
    static_roll = [(n, p) for n, p, _ in mod if not (n in roll_out or n.startswith("yaw_"))]
    yaw_rot = {"yaw_shaft", "yaw_flange"}
    moving_yaw = [(n, p) for n, p, _ in mod if n in yaw_rot] + up
    static_yaw = [(n, p) for n, p, _ in mod if n.startswith("yaw_") and n not in yaw_rot and n != "yaw_stop_pin"]
    return roll, moving_roll, static_roll, moving_yaw, static_yaw


def _near(a, b, pad=8.0):
    ba, bb = a.bounding_box(), b.bounding_box()
    return not (ba.min.X > bb.max.X + pad or bb.min.X > ba.max.X + pad or ba.min.Y > bb.max.Y + pad or bb.min.Y > ba.max.Y + pad
                or ba.min.Z > bb.max.Z + pad or bb.min.Z > ba.max.Z + pad)


def sweep(moving, static, axis, angles):
    worst = {}
    for t in angles:
        for nm, pm in moving:
            q = pm.rotate(axis, t)
            for ns, ps in static:
                if not _near(q, ps):
                    continue
                try:
                    d = q.distance_to(ps)
                except Exception:
                    continue
                k = (nm, ns)
                if k not in worst or d < worst[k][0]:
                    worst[k] = (d, t)
    return worst


def joints():
    """The swept joints in the roll-module frame (robot.build places roll.module() at roll = yaw = 0):
    {joint: (moving, static, axis origin, axis direction, (lo, hi) deg)}. Also used by rnd/pinch.py (R17)."""
    roll, mr, sr, my, sy = _sets()
    from .twin import JR
    return {"roll": (mr, sr, (0, roll.ROLL_Y, 0), (1, 0, 0), tuple(JR["roll"])),
            "yaw": (my, sy, (0, roll.ROLL_Y, 0), (0, 0, 1), (-roll.YAW_STOP_DEG, roll.YAW_STOP_DEG))}


def run(step=10):
    res = {}
    for j, (mv, st, o, d, (lo, hi)) in joints().items():
        stp = step if j == "roll" else 2 * step
        res[j] = sweep(mv, st, Axis(o, d), list(range(lo, hi + 1, stp)) + [hi])
    return res


def main():
    from .spacing import classify, RULES
    res = run()
    rows = []
    for j, w in res.items():
        for (a, b), (d, t) in sorted(w.items(), key=lambda kv: kv[1][0]):
            k = classify(a, b)
            tgt, hard = (TARGET, HARD) if k in ("static", "mate") else RULES[k]
            if d < tgt - 0.005:
                rows.append((j, a, b, d, t, k, tgt, hard))
    nh = sum(1 for r in rows if r[3] < r[7])
    mins = {j: min((v[0] for v in w.values()), default=99) for j, w in res.items()}
    L = ["# Swept spacing over joint ranges (generated by `python -m rnd.swept`)", "", __doc__.split("\n\n", 1)[1].strip(), "",
         f"**Minimum gap over the sweep: roll {mins['roll']:.1f} mm, yaw {mins['yaw']:.1f} mm. Pairs under target: {len(rows)}; under the hard limit: {nh}.**", "",
         "| Joint | Moving part | Static part | Kind | Min gap (mm) | Target / hard | at angle | |", "|---|---|---|---|---|---|---|---|"]
    L += [f"| {j} | {a} | {b} | {k} | {d:.2f} | {tg} / {hd} | {t:.0f}° | {'❌ hard' if d < hd else '⚠️ target'} |" for j, a, b, d, t, k, tg, hd in rows]
    (DOCS / "swept.md").write_text("\n".join(L))
    (DOCS / "swept.json").write_text(json.dumps({"under_target": len(rows), "under_hard": nh, "min": mins}))
    print("\n".join(L[4:]))


if __name__ == "__main__":
    main()
