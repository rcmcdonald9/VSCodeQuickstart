"""Belt-stage sizing for the arm's in-bone reductions (HTD 5M, printed pulleys).

Each stage: small pulley on its own bone-supported hub (driven by a cartridge through KX74), big pulley on the joint hub.
Checks: belt pull at actuator peak vs allowable tension, teeth in mesh, pulley sizes vs bone envelope, belt length.
"""
from __future__ import annotations

import math

from .params import BASELINE, COMP, Design, act

B = COMP["timing_belt_htd5m"]
PITCH = 5.0
MIN_TEETH_IN_MESH = 6


def pd(teeth):                      # pitch diameter, mm
    return teeth * PITCH / math.pi


def stage(joint, ratio, z_small, centre_mm, width_mm, d: Design = BASELINE):
    name, _ = d.arm.joints[joint]
    a = act(name)
    z_big = round(z_small * ratio)
    r_s = pd(z_small) / 2
    pull_peak = a["peak"] * 1000 / r_s             # N, tight-side pull at actuator peak
    pull_rated = a["rated"] * 1000 / r_s
    allow = B["allowable_tension_n_per_10mm"] * width_mm / 10
    # wrap angle on the small pulley and teeth in mesh
    D, dd = pd(z_big), pd(z_small)
    wrap = math.pi - 2 * math.asin((D - dd) / (2 * centre_mm))
    tim = z_small * wrap / (2 * math.pi)
    length = 2 * centre_mm + math.pi * (D + dd) / 2 + (D - dd) ** 2 / (4 * centre_mm)
    return dict(joint=joint, act=name, ratio_exact=z_big / z_small, z=(z_small, z_big), pd=(dd, D), width=width_mm,
                pull_rated=pull_rated, pull_peak=pull_peak, allow=allow, sf_peak=allow / pull_peak,
                tim=tim, centre=centre_mm, length=length, teeth_belt=length / PITCH, outer_big=D + 2 * 3.6)


STAGES = [("shoulder_pitch", 3.0, 20, 70, 15), ("shoulder_roll", 4.0, 18, 90, 15), ("upper_yaw", 2.0, 20, 80, 15), ("elbow", 2.0, 20, 70, 15)]


def report(d: Design = BASELINE):
    L = ["# Belt reductions (auto-generated by `python -m rnd.run_all`)", "",
         f"HTD 5M, fiberglass cord, allowable {B['allowable_tension_n_per_10mm']} N per 10 mm width (vendor tables; ESTIMATE until checked against a Gates manual). "
         "Printed pulleys, small pulley on its own bearing hub (cartridges carry torque only, see [kx](kx.md)). "
         "Precedent: Berkeley Blue's single-stage belt reductions on quasi-direct-drive motors.", "",
         "| Joint | Teeth | Pitch Ø small / big (mm) | Belt | Pull rated / peak (N) | Allowable (N) | Safety at peak | Teeth in mesh | Centre / belt length (mm) |",
         "|---|---|---|---|---|---|---|---|---|"]
    for s in (stage(*x, d=d) for x in STAGES):
        f = "✅" if s["sf_peak"] >= 1.2 else ("⚠️" if s["sf_peak"] >= 1.0 else "❌")
        g = "✅" if s["tim"] >= MIN_TEETH_IN_MESH else "❌"
        L.append(f"| {s['joint']} | {s['z'][0]}:{s['z'][1]} ({s['ratio_exact']:.2f}:1) | {s['pd'][0]:.1f} / {s['pd'][1]:.1f} | {s['width']} mm | "
                 f"{s['pull_rated']:.0f} / {s['pull_peak']:.0f} | {s['allow']:.0f} | {s['sf_peak']:.2f} {f} | {s['tim']:.1f} {g} | {s['centre']} / {s['length']:.0f} (≈{s['teeth_belt']:.0f} T) |")
    L += ["", "- **Pull at peak** assumes the full actuator peak torque reaches the small pulley; the KX seat slips at 12.7 N·m, which caps it.",
          "- **Belt lengths** round to the nearest stock length; a sliding small-pulley hub (slotted bearing housing + screw) sets tension.",
          "- **Rejected this loop:** moving the elbow motor up the upper arm on a long belt (Berkeley Blue-style). The shoulder torque saving is only ~0.5 N·m "
          "(the motor moves 0.14 m) because the 85 % shoulder spring already cancels most self-weight, and the remote layout adds 0.24 kg of pulley hubs to the carry budget."]
    return "\n".join(L)


def score(d: Design = BASELINE):
    return min(stage(*x, d=d)["sf_peak"] for x in STAGES)


if __name__ == "__main__":
    print(report())
