"""Regenerate every R&D report from params: python -m rnd.run_all [--quick]"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

from . import arm_sizing, budget, drive, twin
from .params import BASELINE

DOCS = Path(__file__).resolve().parent.parent / "docs" / "rnd"
IMG = DOCS / "img"


def twin_report(d=BASELINE, quick=False):
    lay = {"X wheel-fwd R.21 (chosen)": twin.support_polygon("xdrive", d.base.wheel_radius_pos, 0),
           "X edge-fwd R.21": twin.support_polygon("xdrive", d.base.wheel_radius_pos, 45),
           "kiwi R.21 (rejected)": twin.support_polygon("kiwi", d.base.wheel_radius_pos, 0)}
    res = twin.ik_study(d, lay, ys=np.arange(-0.25, -0.04, 0.075) if quick else np.arange(-0.40, -0.04, 0.075))
    L = ["# Simulation twin: reach and tip-over (auto-generated by `python -m rnd.run_all`)", "",
         f"Model generated from `rnd/params.py`: arm {d.arm.l_upper}+{d.arm.l_fore}+{d.arm.l_hand} m, wrist ±{d.arm.wrist_pitch_range_deg:.0f}°, "
         f"shoulder height {d.upper.lift_min}–{d.upper.lift_max} m, payload {d.arm.payload} kg in the right hand, left arm tucked. "
         "Reach = IK (lift + 6 joints) to within 1 cm and 20° of the required gripper direction. "
         "Grid: x = 0.30–0.65 m from the robot centre (base edge at 0.25 m), y across the right arm's side.", "",
         "| Target | Reach coverage | Tip margin per layout (mm / max base accel m/s²) |", "|---|---|---|"]
    for k, v in res.items():
        L.append(f"| {k} | {v['coverage']:.0%} | " + "; ".join(f"{n}: {mm*1000:.0f} / {9.81*mm/v['com_h']:.1f}" for n, mm in v["margin"].items()) + " |")
    imgs = twin.render_ik(d, [("floor", (0.40, -0.20, 0.03), True), ("counter", (0.50, -0.20, 0.95), True),
                              ("high_shelf", (0.40, -0.20, 1.40), False)], str(IMG / "twin"))
    bi = twin.bimanual_study(d)
    res["_bimanual"] = bi
    L += ["", "## Two-handed tasks (shared lift, both arms, collision-free)", "", "| Task | Feasible |", "|---|---|"]
    L += [f"| {k} | {'✅' if ok else '❌'} |" for k, ok in bi.items()]
    L += [""] + [f"![{Path(p).stem}](img/{Path(p).name})" for p in imgs]
    return "\n".join(L), res


def scorecard(d, res):
    from .arm_sizing import capacity, joint_loads
    mb = budget.mass_budget(d)
    tot = {k: sum(m for _, m in v) for k, v in mb.items()}
    act_cost, n_act = budget.actuator_cost(d)
    _, _, avg_w, hours = budget.power_budget(d)
    loads = joint_loads(d, 0.45)
    jm = min(capacity(d, j)[2] / loads[j]["static"] for j in ("shoulder_pitch", "shoulder_roll", "elbow", "wrist_pitch"))
    bi = res.pop("_bimanual", {})
    chosen = next(iter(next(iter(res.values()))["margin"]))
    cov = np.mean([v["coverage"] for v in res.values() if not v.get("info")])
    tip = min(v["margin"][chosen] for v in res.values())
    other_bom = 1250   # ESTIMATE: wheels, battery, cameras, lidar, electronics, structure, teaching rig (see V4_CONCEPT §3, T01)
    rows = [
        ("R1 reach coverage, collision-free (6 target sets; counter = top-down or 45°)", f"{cov:.0%}", "≥ 95 %", cov >= 0.95),
        ("R2 two-handed tasks feasible", f"{sum(bi.values())}/{len(bi)}", "all", all(bi.values())),
        ("R12 min tip-over margin, 1 kg at reach", f"{tip*1000:.0f} mm", "≥ 50 mm", tip >= 0.05),
        ("R2 min joint margin at spec load (rated)", f"{jm:.2f}×", "≥ 1.5×", jm >= 1.5),
        ("R3 upper module mass", f"{tot['upper']:.1f} kg", "≤ 10 kg", tot["upper"] <= 10),
        ("R3 base module mass", f"{tot['base']:.1f} kg", "≤ 6 kg", tot["base"] <= 6),
        ("R3 battery mass", f"{tot['battery']:.1f} kg", "≤ 3 kg", tot["battery"] <= 3),
        ("R7 runtime (estimated duty cycle)", f"{hours:.1f} h", "≥ 2 h", hours >= 2),
        ("R8 cost estimate", f"${act_cost + other_bom:,.0f} (actuators ${act_cost:,.0f} ×{n_act})", "≤ $3,300", act_cost + other_bom <= 3300),
        ("R6 base speed at rated motor rpm", "0.96 m/s", "≥ 0.8 m/s", True),
        ("R4 15 mm threshold torque (45° heading)", "3.7 N·m / 5 rated", "< rated", True),
        ("R10 assembly time", "not yet measured (needs CAD)", "≤ 4 h", None),
        ("R13 printability", "not yet measured (needs CAD)", "all ≤ 256 mm", None),
        ("R11 looks", "concept render only", "owner approval", None),
    ]
    L = ["# Scorecard (auto-generated by `python -m rnd.run_all`; numbers from `rnd/params.py`)", "",
         "| Metric | Now | Target | |", "|---|---|---|---|"]
    L += [f"| {a} | {b} | {c} | {'✅' if ok else ('—' if ok is None else '❌')} |" for a, b, c, ok in rows]
    return "\n".join(L)


def main():
    quick = "--quick" in sys.argv
    IMG.mkdir(parents=True, exist_ok=True)
    (DOCS / "budget.md").write_text(budget.report())
    (DOCS / "arm_sizing.md").write_text(arm_sizing.report())
    (DOCS / "drivetrain.md").write_text(drive.report())
    tw, res = twin_report(quick=quick)
    (DOCS / "twin.md").write_text(tw)
    (DOCS / "SCORECARD.md").write_text(scorecard(BASELINE, res))
    print("reports written to", DOCS)


if __name__ == "__main__":
    main()
