def twin_report(d=BASELINE, quick=False):
    lay = {"X wheel-fwd R.21 (chosen)": twin.support_polygon("xdrive", d.base.wheel_radius_pos, 0),
           "X edge-fwd R.21": twin.support_polygon("xdrive", d.base.wheel_radius_pos, 45),
           "kiwi R.21 (rejected)": twin.support_polygon("kiwi", d.base.wheel_radius_pos, 0)}
    res = twin.ik_study(d, lay, ys=np.arange(-0.25, -0.04, 0.075) if quick else np.arange(-0.40, -0.04, 0.075))
    L = ["# Simulation twin: reach and tip-over (auto-generated by `python -m rnd.run_all`)", "",
         f"Model generated from `rnd/params.py`: arm {d.arm.l_upper}+{d.arm.l_fore}+{d.arm.l_hand} m, wrist ±{d.arm.wrist_pitch_range_deg:.0f}°, "
         f"shoulder height {d.upper.lift_min}–{d.upper.lift_max} m, payload {d.arm.payload} kg in the right hand, left arm tucked. "
         "Reach = IK (lift + 6 joints) to within 1 cm and 20° of the required gripper direction. "
         "Grid: x = 0.30–0.65 m from the robot centre (base edge at 0.25 m), y across the right arm's side.", "",
         "| Target | Reach coverage | Tip margin per layout (mm / max base accel m/s²) |", "|---|---|---|"]
    for k, v in res.items():
        L.append(f"| {k} | {v['coverage']:.0%} | " + "; ".join(f"{n}: {mm*1000:.0f} / {9.81*mm/v['com_h']:.1f}" for n, mm in v["margin"].items()) + " |")
    imgs = twin.render_ik(d, [("floor", (0.40, -0.20, 0.03), True), ("counter", (0.50, -0.20, 0.95), True),
                              ("high_shelf", (0.40, -0.20, 1.40), False)], str(IMG / "twin"))
    bi = twin.bimanual_study(d)
    res["_bimanual"] = bi
    L += ["", "## Two-handed tasks (shared lift, both arms, collision-free)", "", "| Task | Feasible |", "|---|---|"]
    L += [f"| {k} | {'✅' if ok else '❌'} |" for k, ok in bi.items()]
    L += [""] + [f"![{Path(p).stem}](img/{Path(p).name})" for p in imgs]
    return "\n".join(L), res


def _build_rows():
    import json
    f, g = DOCS / "build.json", DOCS / "bom.json"
    rows = []
    if f.exists():
        h = json.loads(f.read_text())["hours"]
        rows.append(("R10 first-build hands-on time (estimate, BUILD_v4.md)", f"{h:.0f} h", "≤ 4 h", h <= 4))
    if g.exists():
        t = json.loads(g.read_text())["total"]
        rows.append(("R8 cost from the itemised BOM (BOM_v4.md)", f"${t:,.0f}", "≤ $4,000 (D9; limit $5,000)", t <= 4000))
    return rows


def _threshold_rows():
    import json
    f = DOCS / "threshold.json"
    if not f.exists():
        return []
    a = json.loads(f.read_text())
    return [("R4 sim: 15 mm threshold on hard floor + carpet (45°, ≤ 0.15 m/s), peak margin", f"{'crossed' if a['ok15'] else 'FAILED'}, {11 / a['peak15']:.1f}×", "cross, ≥ 1.5×", a["ok15"] and 11 / a["peak15"] >= 1.5),
            ("R4 sim: carpet cruise wheel torque (RMS / rated)", f"{a['cruise_rms_carpet']:.1f} / 5 N·m", "≤ 70 %", a["cruise_rms_carpet"] <= 3.5)]


def _sim_rows():
    import json
    f = DOCS / "sim.json"
    if not f.exists():
        return [("Twin v1 dynamic fetch task", "run `python -m rnd.sim`", "success", None)]
    a = json.loads(f.read_text())
    return [("Twin v1: drive + pick from floor + place on table (dynamic, real actuator limits)", "success" if a["ok"] else "FAILED", "success", a["ok"]),
            ("Twin v1: robustness (±15 mm perception error, 0.2–0.6 kg)", f"{a['sweep_ok']}/{a['sweep_n']}", "all", a["sweep_ok"] == a["sweep_n"]),
            ("Twin v1: worst actuator use, peak / continuous (RMS vs rated)", f"{a['peak_use']:.0%} / {a['rms_use']:.0%}", "≤ 80 % / ≤ 70 %", a["peak_use"] <= 0.8 and a["rms_use"] <= 0.7),
            ("Twin v1: min dynamic tip margin (ZMP)", f"{a['zmp_min'] * 1000:.0f} mm", "≥ 30 mm", a["zmp_min"] >= 0.03)]


