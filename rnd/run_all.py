def scorecard(d, res):
    from .arm_sizing import capacity, joint_loads
    mb = budget.mass_budget(d)
    tot = {k: sum(m for _, m in v) for k, v in mb.items()}
    act_cost, n_act = budget.actuator_cost(d)
    _, _, avg_w, hours = budget.power_budget(d)
    loads = joint_loads(d, 0.45)
    jm = min(capacity(d, j)[2] / loads[j]["static"] for j in ("shoulder_pitch", "shoulder_roll", "elbow", "wrist_pitch"))
    bi = res.pop("_bimanual", {})
    chosen = next(iter(next(iter(res.values()))["margin"]))
    cov = np.mean([v["coverage"] for v in res.values() if not v.get("info")])
    tip = min(v["margin"][chosen] for v in res.values())
    kx_slip, kx_sock = kx_check.score(d)
    belt_sf = belts.score(d)
    ws_r, ws_p = spring.score(d)
    other_bom = 1250   # ESTIMATE: wheels, battery, cameras, lidar, electronics, structure, teaching rig (see V4_CONCEPT §3, T01)
    other_bom -= 80    # loop 8: lift NEMA23 kit + brake (~$88, part of the 1250) replaced by a GIM (now in actuators) + ratchet/solenoid (~$8)
    other_bom += 25    # loop 9: CF tubes Ø40 + Ø30 for two arms (ESTIMATE)
    other_bom += 100   # KX v1 hardware (ESTIMATE): ~16 sockets × (2 thin bearings + 6 pins + 3 balls + spring + PTFE washer)
    rows = [
        ("R1 reach coverage, collision-free (6 target sets; counter = top-down or 45°)", f"{cov:.0%}", "≥ 95 %", cov >= 0.95),
        ("R2 two-handed tasks feasible", f"{sum(bi.values())}/{len(bi)}", "all", all(bi.values())),
        ("R12 min tip-over margin, 1 kg at reach", f"{tip*1000:.0f} mm", "≥ 50 mm", tip >= 0.05),
        ("R2 min joint margin at spec load (rated, planar check)", f"{jm:.2f}×", "≥ 1.5×", jm >= 1.5),
        ("R3 upper core (arms detached)" if "arm (each, detachable)" in tot else "R3 upper module mass", f"{tot['upper']:.1f} kg", "≤ 10 kg", tot["upper"] <= 10),
        *((("R3 each arm (detaches at the shoulder KX)", f"{tot['arm (each, detachable)']:.1f} kg", "≤ 10 kg", tot['arm (each, detachable)'] <= 10),)
          if "arm (each, detachable)" in tot else ()),
        ("R3 assembled upper (core + arms, for reference)", f"{budget.upper_total(mb):.1f} kg", "info", None),
        ("R3 base module mass", f"{tot['base']:.1f} kg", "≤ 8 kg (piece limit 10)", tot["base"] <= 8),
        ("R3 battery mass", f"{tot['battery']:.1f} kg", "≤ 3 kg", tot["battery"] <= 3),
        ("R7 runtime (estimated duty cycle)", f"{hours:.1f} h", "≥ 2 h", hours >= 2),
        ("R8 cost, parametric estimate (superseded by the BOM row)", f"${act_cost + other_bom:,.0f} (actuators ${act_cost:,.0f} ×{n_act})", "info", None),
        ("R9 KX interface slip torque / actuator peak (min)", f"{kx_slip:.2f}×", "≥ 1.1×", kx_slip >= 1.1),
        ("R2 min joint margin, whole workspace (rated / 95th pct, 1 kg)", f"{ws_r:.2f}×", "≥ 1.5×", ws_r >= 1.5),
        ("R2 min joint margin, whole workspace (peak / worst pose)", f"{ws_p:.2f}×", "≥ 1.5×", ws_p >= 1.5),
        ("R2 hand sag from bone bending, 1 kg straight out (static)", f"{bones.score(d)[1]:.1f} mm", "≤ 2 mm", bones.score(d)[1] <= 2.0),
        ("R2 belts: sustained pull vs working rating / peak vs ultimate (min)", f"{belt_sf[0]:.1f}× / {belt_sf[1]:.1f}×", "≥ 1.2× / ≥ 3×", belt_sf[0] >= 1.2 and belt_sf[1] >= 3),
        ("R3 arm-detach clamp: lift-off moment / need (×1.5 dynamic)", f"{kx_check.detach_score(d):.1f}×", "≥ 1.5×", kx_check.detach_score(d) >= 1.5),
        ("R12 socket bearing static safety (min)", f"{kx_sock:.1f}", "≥ 2", kx_sock >= 2),
        ("R2 hand positioning error, joint chain RSS at 0.6 m (with joint-side encoders; without)", f"{accuracy.score(d)[0]:.1f} mm ({accuracy.score(d)[1]:.1f})", "≤ 2 mm", accuracy.score(d)[0] <= 2),
        ("R2 torso sway from mast bending (worst static)", f"{mast.score(d)[0]:.1f} mm", "≤ 2 mm", mast.score(d)[0] <= 2.0),
        ("R5 lift: torque margin / full-travel time", f"{lift.score(d)[0]:.2f}× / {lift.score(d)[1]:.1f} s", "≥ 1.5× / ≤ 6 s", lift.score(d)[0] >= 1.5 and lift.score(d)[1] <= 6),
        ("R6 base speed at rated motor rpm", "0.96 m/s", "≥ 0.8 m/s", True),
        ("R4 15 mm threshold: peak torque margin (transient < 1 s)", f"{11 / drive.threshold_torque_45(d):.1f}× ({drive.threshold_torque_45(d):.1f} of 11 N·m peak)", "≥ 1.5×", 11 / drive.threshold_torque_45(d) >= 1.5),
        *_build_rows(),
        *_assembly_rows(),
        *_sim_rows(),
        *_threshold_rows(),
        *_confidence_rows(),
        ("R11 looks", "engineering render v0 (robot_v0.png); industrial-design pass pending", "owner approval", None),
    ]
    L = ["# Scorecard (auto-generated by `python -m rnd.run_all`; numbers from `rnd/params.py`)", "",
         "| Metric | Now | Target | |", "|---|---|---|---|"]
    L += [f"| {a} | {b} | {c} | {'✅' if ok else ('—' if ok is None else '❌')} |" for a, b, c, ok in rows]
    return "\n".join(L)


def main():
    quick = "--quick" in sys.argv
    IMG.mkdir(parents=True, exist_ok=True)
    (DOCS / "budget.md").write_text(budget.report())
    (DOCS / "arm_sizing.md").write_text(arm_sizing.report())
    (DOCS / "drivetrain.md").write_text(drive.report())
    (DOCS / "belts.md").write_text(belts.report() + "\n\n![elbow belt stage: cartridge M on its pulley hub, 20T→40T HTD 5M](img/elbow_belt_stage.png)\n")
    (DOCS / "spring.md").write_text(spring.report())
    (DOCS / "lift.md").write_text(lift.report())
    (DOCS / "mast.md").write_text(mast.report())
    (DOCS / "accuracy.md").write_text(accuracy.report())
    (DOCS / "bones.md").write_text(bones.report())
    (DOCS / "balancer.md").write_text(balancer.report() + "\n\n![shoulder pitch module](img/shoulder_pitch_v0.png)\n")
    (DOCS / "kx.md").write_text(kx_check.report() + "\n\n![cartridges M and S, exploded](img/cartridge_m_exploded.png)\n")
    tw, res = twin_report(quick=quick)
    (DOCS / "twin.md").write_text(tw)
    (DOCS / "SCORECARD.md").write_text(scorecard(BASELINE, res))
    print("reports written to", DOCS)


if __name__ == "__main__":
    main()
