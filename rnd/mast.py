"""Mast sizing: bending of the vertical spine under the torso + arms + payload (worst: torso at the top, both arms out).

Cantilever from the base coupling; the deflection at the torso moves both hands. Options are stock tubes/extrusions.
"""
from __future__ import annotations

from .budget import mass_budget
from .params import BASELINE, Design, G

E_AL, E_CF = 69e3, 70e3   # MPa


def rect_tube(b, t):
    return (b ** 4 - (b - 2 * t) ** 4) / 12, 4 * (b - t) * t * 1e-6 * 2700        # I mm⁴, kg/m


OPTIONS = {
    "2040 extrusion (v0 placeholder)": (69_000, 0.50, E_AL),       # Ix ≈ 6.9 cm⁴ (ESTIMATE, typical catalogue), 0.5 kg/m
    "40×40×2 Al square tube": (*rect_tube(40, 2), E_AL),
    "50×50×2 Al square tube": (*rect_tube(50, 2), E_AL),
    "60×60×2 Al square tube": (*rect_tube(60, 2), E_AL),
}
CHOICE = "60×60×2 Al square tube"
SWAY_TARGET = 2.0   # mm at the torso under the worst static case


def moment(d: Design = BASELINE) -> float:
    """Worst static bending moment at the mast foot (N·m): both arms straight forward with 1 kg each, torso at the top."""
    from .arm_sizing import point_masses
    pts, _ = point_masses(d)
    arm_moment = sum(m * G * (x + d.arm.shoulder_x + 0.06) for _, m, x in pts)          # arm masses ahead of the mast
    mb = mass_budget(d)
    torso = sum(m for n, m in mb["upper"] if n not in ("spine extrusion", "lift motor", "handle", "coupling (upper half)", "head"))
    return 2 * arm_moment + torso * G * 0.06                                           # torso CoM ~60 mm ahead of the mast


def report(d: Design = BASELINE) -> str:
    M = moment(d)
    L_ = d.upper.spine_len
    rows = ["# Mast (auto-generated by `python -m rnd.run_all`)", "",
            f"Worst static moment at the mast foot: **{M:.0f} N·m** (both arms straight forward with 1 kg each, torso at the top of {L_:.2f} m). "
            f"Target: torso sway ≤ {SWAY_TARGET} mm.", "",
            "| Option | I (mm⁴) | kg/m | Sway at the torso | Stress |", "|---|---|---|---|---|"]
    for n, (I, kgm, E) in OPTIONS.items():
        sway = M * 1000 * (L_ * 1000) ** 2 / (2 * E * I)
        b = float(n.split("×")[0].split()[-1]) if "×" in n else 40
        sigma = M * 1000 * (b / 2) / I
        star = " **← chosen**" if n == CHOICE else ""
        rows.append(f"| {n}{star} | {I:,.0f} | {kgm:.2f} | {sway:.1f} mm {'✅' if sway <= SWAY_TARGET else '⚠️'} | {sigma:.0f} MPa |")
    rows += ["", "The carriage runs on 8 × 625 bearings (two per face, top and bottom) on the tube's flat faces; the square section also stops the torso from turning.",
             "The lift belt (HTD 5M, motor fixed at the mast foot, idler inside the head) and the printed ratchet strip run on the tube's back face."]
    return "\n".join(rows)


def score(d: Design = BASELINE):
    I, kgm, E = OPTIONS[CHOICE]
    return moment(d) * 1000 * (d.upper.spine_len * 1000) ** 2 / (2 * E * I), kgm


if __name__ == "__main__":
    print(report())
