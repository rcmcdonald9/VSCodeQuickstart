"""Shoulder gravity-balance study: how much of the arm's weight can a pitch-only spring really cancel?

arm_sizing.py assumed a spring cancels a fixed 85 % of the arm's self-weight moment in every pose. A real balancer
gives τ_s = K·sin(pitch) (zero-free-length spring + cable, the Anglepoise / Herder gravity-balancing principle).
When the elbow bends or the arm rolls sideways, the arm's centre of mass moves and the balance drifts.

This samples the joint space (MuJoCo twin, static gravity torques), fits K, and reports the motor torque left over.
"""
from __future__ import annotations

import math

import numpy as np

from .arm_sizing import BELT_EFF
from .params import BASELINE, Design, act
from .twin import JR, build_xml, mujoco

N = 6000
SEED = 4


def _model(d):
    m = mujoco.MjModel.from_xml_string(build_xml(d))
    return m, mujoco.MjData(m)


def gravity_torques(d: Design, n=N, seed=SEED, pitch_range=None):
    """Static pitch-joint torque (N·m, at the joint) for random right-arm poses. Returns (pitch_rad, torque)."""
    m, dat = _model(d)
    rng = np.random.default_rng(seed)
    jid = {j: mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, f"{j}_r") for j in ("pitch", "roll", "yaw", "elbow", "wpitch", "wroll")}
    lo, hi = pitch_range or JR["pitch"]
    ranges = {"pitch": (lo, hi), "roll": JR["roll"], "yaw": JR["yaw"], "elbow": JR["elbow"],
              "wpitch": (-d.arm.wrist_pitch_range_deg, d.arm.wrist_pitch_range_deg), "wroll": (0, 0)}
    p_out, t_out = np.empty(n), np.empty(n)
    for i in range(n):
        dat.qpos[:] = 0
        dat.qvel[:] = 0
        for j, (a, b) in ranges.items():
            dat.qpos[m.jnt_qposadr[jid[j]]] = math.radians(rng.uniform(a, b))
        mujoco.mj_forward(m, dat)
        p_out[i] = dat.qpos[m.jnt_qposadr[jid["pitch"]]]
        t_out[i] = dat.qfrc_bias[m.jnt_dofadr[jid["pitch"]]]
    return p_out, t_out


JOINTS = {"pitch": "shoulder_pitch", "roll": "shoulder_roll", "yaw": "upper_yaw", "elbow": "elbow", "wpitch": "wrist_pitch"}


def workspace_torques(d: Design = BASELINE, n=N, seed=SEED):
    """|static torque| per joint over random poses (payload included). The pitch joint includes the balancer."""
    m, dat = _model(d)
    rng = np.random.default_rng(seed)
    jid = {j: mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, f"{j}_r") for j in JOINTS}
    ranges = {"pitch": JR["pitch"], "roll": JR["roll"], "yaw": JR["yaw"], "elbow": JR["elbow"],
              "wpitch": (-d.arm.wrist_pitch_range_deg, d.arm.wrist_pitch_range_deg)}
    T = {j: np.empty(n) for j in JOINTS}
    for i in range(n):
        dat.qpos[:] = 0
        dat.qvel[:] = 0
        for j, (a, b) in ranges.items():
            dat.qpos[m.jnt_qposadr[jid[j]]] = math.radians(rng.uniform(a, b))
        mujoco.mj_forward(m, dat)
        for j in JOINTS:
            t = dat.qfrc_bias[m.jnt_dofadr[jid[j]]]
            if j == "pitch":
                t -= d.arm.spring_k_nm * math.sin(dat.qpos[m.jnt_qposadr[jid[j]]])
            T[j][i] = abs(t)
    return T


def workspace_margins(d: Design = BASELINE):
    from .arm_sizing import capacity
    T = workspace_torques(d)
    out = {}
    for j, full in JOINTS.items():
        name, ratio, rated, peak, _ = capacity(d, full)
        p95, mx = float(np.quantile(T[j], .95)), float(T[j].max())
        out[full] = dict(act=name, ratio=ratio, p95=p95, max=mx, rated=rated, peak=peak, m_rated=rated / p95, m_peak=peak / mx)
    return out


def fit_balancer(p, t):
    """Least-squares K for τ_s = K·sin(p) (spring cancels the arm's own weight)."""
    s = np.sin(p)
    return float(np.dot(s, t) / np.dot(s, s))


def study(d: Design = BASELINE):
    d0 = d.copy(**{"arm.payload": 1e-4})
    p0, t0 = gravity_torques(d0)
    K_fit = fit_balancer(p0, t0)
    K = d.arm.spring_k_nm
    p1, t1 = gravity_torques(d)                       # same poses (same seed) with the payload
    res0, res1 = t0 - K * np.sin(p0), t1 - K * np.sin(p1)
    name, ratio = d.arm.joints["shoulder_pitch"]
    a = act(name)
    cap_rated, cap_peak = a["rated"] * ratio * BELT_EFF, a["peak"] * ratio * BELT_EFF
    q = lambda x, k: float(np.quantile(np.abs(x), k))
    return dict(K=K, K_fit=K_fit, cap_rated=cap_rated, cap_peak=cap_peak,
                no_spring=dict(p95=q(t1, .95), max=q(t1, 1.0)),
                arm_only=dict(p95=q(res0, .95), max=q(res0, 1.0), share=1 - q(res0, .95) / q(t0, .95)),
                with_payload=dict(p95=q(res1, .95), max=q(res1, 1.0)))


def report(d: Design = BASELINE) -> str:
    s = study(d)
    L = ["# Shoulder spring balance (auto-generated by `python -m rnd.run_all`)", "",
         f"{N} random right-arm poses across the full joint ranges (MuJoCo twin, static). A pitch-only balancer τ = K·sin(pitch) "
         "(zero-free-length spring + cable: Anglepoise / Herder gravity balancing) is fitted to the arm's own weight.", "",
         f"**Design K = {s['K']:.2f} N·m** (spring torque at the horizontal arm; `params.arm.spring_k_nm`). "
         f"A least-squares fit to the bare arm gives {s['K_fit']:.2f} N·m; a K sweep showed 4.0 minimises the 95th-percentile motor torque "
         "for a 0.5 kg typical payload (0.5 kg: 5.2 N·m; 1 kg: 7.3 N·m). The spring preload is screw-adjustable (Anglepoise precedent), so K can be re-tuned per task.", "",
         "| Motor torque needed at the pitch joint | 95th percentile | Worst pose |", "|---|---|---|",
         f"| No spring, 1 kg payload | {s['no_spring']['p95']:.1f} N·m | {s['no_spring']['max']:.1f} N·m |",
         f"| Spring, arm only | {s['arm_only']['p95']:.1f} N·m | {s['arm_only']['max']:.1f} N·m |",
         f"| **Spring, 1 kg payload** | **{s['with_payload']['p95']:.1f} N·m** | **{s['with_payload']['max']:.1f} N·m** |",
         f"| Joint capacity (GIM6010-8 × {BASELINE.arm.joints['shoulder_pitch'][1]} belt), rated / peak | {s['cap_rated']:.1f} | {s['cap_peak']:.1f} |", "",
         f"The spring cancels **{s['arm_only']['share']:.0%}** of the arm's self-weight torque at the 95th percentile (arm_sizing assumed 85 % everywhere).",
         f"Margin with payload: rated / 95th pct **{s['cap_rated'] / s['with_payload']['p95']:.2f}×**, peak / worst pose **{s['cap_peak'] / s['with_payload']['max']:.2f}×**.", "",
         "## Every arm joint over the whole workspace (1 kg payload, static, balancer on)", "",
         "The planar check in [arm sizing](arm_sizing.md) only looks at a straight horizontal arm. That pose never loads the upper-arm yaw, "
         "which holds the forearm + payload whenever the elbow is bent and the upper arm is not vertical (on a Franka arm that joint is as strong as the shoulder).", "",
         "| Joint | Actuator × ratio | Need: 95th pct / worst (N·m) | Rated / peak | Margin rated/p95 | Margin peak/worst |", "|---|---|---|---|---|---|"]
    for j, r in workspace_margins(d).items():
        f = "✅" if r["m_rated"] >= 1.5 and r["m_peak"] >= 1.5 else ("⚠️" if r["m_rated"] >= 1.0 and r["m_peak"] >= 1.0 else "❌")
        L.append(f"| {j} | {r['act']} × {r['ratio']:g} | {r['p95']:.1f} / {r['max']:.1f} | {r['rated']:.1f} / {r['peak']:.1f} | {r['m_rated']:.2f} | {r['m_peak']:.2f} {f} |")
    L += ["", "**Loop 5 change:** upper-arm yaw DM-J4310 direct (rated/p95 0.65×, ❌) → **GIM6010-8 × 2 belt**. "
          "It's cheaper (~$70 per arm), backdrivable, the same part as the other big joints, and adds +0.29 kg per arm. "
          "Considered: DM-J4340P direct (1.96×, +70 g, +$29, but 40:1 gearing is barely backdrivable)."]
    return "\n".join(L)


def score(d: Design = BASELINE):
    w = workspace_margins(d)
    return min(r["m_rated"] for r in w.values()), min(r["m_peak"] for r in w.values())


if __name__ == "__main__":
    print(report())
