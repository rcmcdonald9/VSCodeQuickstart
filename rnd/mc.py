"""Monte Carlo of the dynamic fetch task with realistic imperfections.  python -m rnd.mc [N]

Each run draws:
- motor torque derating 0.75–1.0 (all arm, lift and base actuators)
- arm mass ×1.0–1.25 (printed parts heavier than CAD)
- joint friction 0–0.6 N·m (gear and belt drag, the GIM cogging stand-in)
- joint zero-calibration errors σ 0.1° per joint (with joint-side encoders; ESTIMATE)
- finger-object friction μ 0.5–1.2
- can mass 0.2–0.6 kg
- can position error ±15 mm vs the robot's belief

The wrist camera re-measures with σ 3 mm, as designed.
Pass: the can ends upright on the table, with no robot–table contact.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np

from . import sim

DOCS = Path(__file__).resolve().parent.parent / "docs" / "rnd"


def draw(rng):
    return dict(derate=rng.uniform(0.75, 1.0), mass=rng.uniform(1.0, 1.25), joint_friction=rng.uniform(0.0, 0.6),
                calib=rng.normal(0, math.radians(0.1), len(sim.ARM)), finger_mu=rng.uniform(0.5, 1.2),
                can_mass=rng.uniform(0.2, 0.6), offset=tuple(rng.uniform(-0.015, 0.015, 2)))


def one(kp):
    k, p = kp
    L = sim.limits()
    r = sim.run(video=False, can_offset=p["offset"], can_mass=p["can_mass"], seed=k, perturb=p)
    ok = r["ok"] and not r["table_hits"]
    peak = max(np.max(r["force"][nm]) / (L[nm][1] * p["derate"]) for nm in r["force"] if nm != "a_fing_a_r")
    row = dict(ok=ok, derate=p["derate"], mass=p["mass"], fric=p["joint_friction"], mu=p["finger_mu"], can=p["can_mass"],
               off=p["offset"], peak=float(peak), zmp=float(r["zmp"].min()))
    print(k, "ok" if ok else "FAIL", {kk: (round(v, 3) if isinstance(v, float) else v) for kk, v in row.items() if kk != "off"}, flush=True)
    return row


def main(n=30, seed=7, workers=4):
    from multiprocessing import Pool
    rng = np.random.default_rng(seed)
    draws = [draw(rng) for _ in range(n)]
    with Pool(workers) as pool:
        rows = pool.map(one, list(enumerate(draws)))
    ns = sum(r["ok"] for r in rows)
    # Wilson 95 % lower bound on the success rate
    z, ph = 1.96, ns / n
    lb = (ph + z * z / (2 * n) - z * math.sqrt(ph * (1 - ph) / n + z * z / (4 * n * n))) / (1 + z * z / n)
    fails = [r for r in rows if not r["ok"]]
    md = ["# Monte Carlo: dynamic fetch task with imperfections (generated by `python -m rnd.mc`)", "",
          __doc__.split("\n\n", 1)[1].strip(), "",
          f"**{ns}/{n} runs succeed ({ns / n:.0%}; 95 % lower bound {lb:.0%}).** Worst actuator use (of the derated peak): "
          f"{max(r['peak'] for r in rows):.0%}. Min dynamic tip margin {min(r['zmp'] for r in rows) * 1000:.0f} mm.", "",
          "| Run | Result | Torque derate | Arm mass × | Joint friction (N·m) | Finger μ | Can kg | Can offset (mm) | Peak use | Tip margin (mm) |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    md += [f"| {i} | {'✅' if r['ok'] else '❌'} | {r['derate']:.2f} | {r['mass']:.2f} | {r['fric']:.2f} | {r['mu']:.2f} | {r['can']:.2f} | "
           f"{r['off'][0] * 1000:+.0f}, {r['off'][1] * 1000:+.0f} | {r['peak']:.0%} | {r['zmp'] * 1000:.0f} |" for i, r in enumerate(rows)]
    if fails:
        md += ["", "**Failures:** " + "; ".join(f"derate {r['derate']:.2f}, μ {r['mu']:.2f}, can {r['can']:.2f} kg" for r in fails)]
    (DOCS / "mc.md").write_text("\n".join(md))
    (DOCS / "mc.json").write_text(json.dumps({"n": n, "ok": ns, "lb95": lb, "peak": max(r["peak"] for r in rows),
                                              "zmp": min(r["zmp"] for r in rows)}))
    print(md[4])


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 30)
