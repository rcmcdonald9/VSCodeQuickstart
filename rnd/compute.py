"""Compute + I/O budget: can the owner's Raspberry Pi 5 run the robot, and what to reserve for the AI phase.  python -m rnd.compute

Stream rates are ESTIMATEs from the sensor formats. Pi 5: 2 × USB 3.0 (simultaneous 5 Gbps), 2 × USB 2.0, 4 × Cortex-A76 at
2.4 GHz, no hardware MJPEG/H.264 decode. A Jetson-class module (e.g. Orin Nano Super 8 GB: 67 INT8 TOPS, 7–25 W) is the usual
step up for on-robot neural policies (precedent: many LeRobot / ACT / VLA deployments use a GPU host).
"""
from __future__ import annotations

from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "docs" / "rnd"

STREAMS = [  # (name, port, Mbit/s, CPU % of one A76 core to ingest)
    ("Head RGB-D (Gemini 2): depth 640×400×16 bit @30 + RGB 1280×800 MJPEG @30", "USB3 #1", 123 + 60, 25),
    ("Wrist camera L: OV9281 1280×800 mono MJPEG @60", "USB3 #2 (hub)", 80, 35),
    ("Wrist camera R: same", "USB3 #2 (hub)", 80, 35),
    ("Lidar (RPLIDAR C1)", "USB2", 0.5, 2),
    ("CAN A via USB-CAN (base + lift + base sensor node), 500 Hz", "USB2", 0.7, 8),
    ("CAN B + C via 2-CH CAN FD HAT (arms + arm sensor nodes), 500 Hz", "SPI", 1.4, 20),
    ("3 × TTL bus-servo adapters (wrists, grippers, head)", "USB2", 0.3, 4),
    ("Mic array + speaker", "USB2", 1.5, 3),
]
CONTROL = [("Joint servo loops: 27 actuators @ 500 Hz (on-motor FOC; host sends targets)", 30),
           ("Whole-body IK + collision checks @ 100 Hz", 60), ("State estimation (wheel odometry + IMU + flow + lidar)", 30),
           ("Safety supervisor, logging, ROS 2 middleware", 40)]
POLICY = [("ACT-class policy (~80 M params) @ 30 Hz", "≈ 1–3 Hz on Pi 5 CPU (ESTIMATE)", "≥ 30 Hz on Orin Nano"),
          ("Diffusion policy (~250 M) @ 10 Hz", "too slow", "≈ 10 Hz on Orin Nano (ESTIMATE)"),
          ("VLA (1–3 B params)", "no", "Orin Nano: marginal; desktop GPU / cloud offload")]


def report():
    usb3 = {}
    for n, port, mb, cpu in STREAMS:
        usb3[port] = usb3.get(port, 0) + mb
    cpu = sum(c for *_, c in STREAMS) + sum(c for _, c in CONTROL)
    L = ["# Compute and I/O budget (auto-generated by `python -m rnd.compute`)", "",
         __doc__.split("\n\n", 1)[1].strip(), "",
         "| Stream | Port | Mbit/s | CPU (% of one core) |", "|---|---|---|---|"]
    L += [f"| {n} | {p} | {mb:g} | {c} |" for n, p, mb, c in STREAMS]
    L += ["", "| Port | Load | Capacity |", "|---|---|---|"]
    cap = {"USB3 #1": 5000, "USB3 #2 (hub)": 5000, "USB2": 480, "SPI": 20}
    L += [f"| {p} | {v:.0f} Mbit/s | {cap[p]} Mbit/s ({v / cap[p]:.0%}) |" for p, v in usb3.items()]
    L += ["", "| Control task | CPU (% of one core) |", "|---|---|"] + [f"| {n} | {c} |" for n, c in CONTROL]
    L += [f"| **Total I/O + control** | **{cpu} % of one core ≈ {cpu / 400:.0%} of the Pi 5** |", "",
          "| Learned policy (AI phase) | Pi 5 | Jetson Orin Nano Super |", "|---|---|---|"] + [f"| {a} | {b} | {c} |" for a, b, c in POLICY]
    L += ["", "**Decision D10:**",
          f"- **The Pi 5 is enough for the hardware phase, but tight:** I/O + control use ≈ {cpu / 400:.0%} of its four cores (ESTIMATE); the USB ports stay below 5 % busy.",
          "- The Jetson bay can also take the wrist-camera ingest if the Pi runs hot.",
          "- **The torso reserves a bay for a Jetson-class AI computer** (mount 105 × 95 × 40 mm above the Pi tray, a 24 → 19 V 3 A branch, Ethernet to the Pi, a vent path).",
          "- Bought only in the AI phase (≈ $249, owner decision). The Pi keeps real-time duties; the Jetson runs the policies."]
    return "\n".join(L)


if __name__ == "__main__":
    md = report()
    (DOCS / "compute.md").write_text(md)
    print(md)
