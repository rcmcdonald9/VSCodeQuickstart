"""Threshold / carpet Monte Carlo with the roller-level omni model (queue item 6, loop 30).  python -m rnd.threshold_mc [N]

It reuses rnd/threshold.py's model. Each run draws:
- threshold height U(5, 18) mm: the design limit is 15 mm, so 15–18 mm probes beyond it
- heading 45° ± U(10°): the planner rule D2b, imperfectly executed
- speed U(0.12, 0.18) m/s (rule: ≤ 0.15)
- hard floor or carpet (50/50)
- floor/roller friction μ ×U(0.6, 1.1)
- robot mass 25.6 kg + U(−1, +4): heavier payloads and real parts
- COM height U(0.35, 0.50) m: lift up or down

Pass: it crosses within 1.6× the ideal travel time + 2 s, peak wheel torque ≤ the GIM peak (11 N·m, the actuator limit in the model), and the body
tilts < 15°.
Reported: the success rate by threshold band, and the torque margin (11 / peak) distribution.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np

DOCS = Path(__file__).resolve().parent.parent / "docs" / "rnd"


def one(args):
    k, p = args
    import mujoco
    from . import threshold as th
    xml = th.build(step_h=p["h"], heading_deg=p["head"], carpet=p["carpet"], mass=p["mass"], com_h=p["com"])
    xml = xml.replace('friction="0.9 0.01 0.0005"', f'friction="{0.9 * p["mu"]:.3f} 0.01 0.0005"').replace(
        'friction="0.7 0.02 0.004"', f'friction="{0.7 * p["mu"]:.3f} 0.02 0.004"')
    m = mujoco.MjModel.from_xml_string(xml)
    d = mujoco.MjData(m)
    mujoco.mj_forward(m, d)
    rb = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_BODY, "robot")
    yaw = math.radians(-p["head"])
    vx, vy = p["v"] * math.cos(-yaw), p["v"] * math.sin(-yaw)
    ww = [-(-math.sin(math.radians(90 * j)) * vx + math.cos(math.radians(90 * j)) * vy) / th.R_W for j in range(4)]
    peak, crossed, tilt_max = 0.0, None, 0.0
    goal = th.STEP_X + th.BASELINE.base.wheel_radius_pos + th.R_W + 0.05
    t_max = 1.6 * goal / p["v"] + 2.0                                              # rollers slip on carpet: allow 60 % slower progress
    for i in range(int(t_max / m.opt.timestep)):
        ramp = min(1.0, i * m.opt.timestep / 0.5)
        d.ctrl[:4] = [w * ramp for w in ww]
        mujoco.mj_step(m, d)
        if i % 20 == 0:
            peak = max(peak, float(np.abs(d.actuator_force[:4]).max()))
            tilt_max = max(tilt_max, math.degrees(math.acos(max(-1, min(1, d.xmat[rb].reshape(3, 3)[2, 2])))))
        if crossed is None and d.xpos[rb][0] > goal:
            crossed = i * m.opt.timestep
            break
    ok = crossed is not None and tilt_max < 15
    row = dict(ok=ok, peak=peak, tilt=tilt_max, **p)
    print(k, "ok" if ok else "FAIL", {kk: round(v, 3) if isinstance(v, float) else v for kk, v in row.items()}, flush=True)
    return row


def main(n=80, seed=5, workers=4):
    from multiprocessing import Pool
    rng = np.random.default_rng(seed)
    draws = [dict(h=float(rng.uniform(0.005, 0.018)), head=float(45 + rng.uniform(-10, 10)), v=float(rng.uniform(0.12, 0.18)),
                  carpet=bool(rng.random() < 0.5), mu=float(rng.uniform(0.6, 1.1)), mass=float(25.6 + rng.uniform(-1, 4)),
                  com=float(rng.uniform(0.35, 0.50))) for _ in range(n)]
    with Pool(workers) as pool:
        rows = pool.map(one, list(enumerate(draws)))
    within = [r for r in rows if r["h"] <= 0.015]
    beyond = [r for r in rows if r["h"] > 0.015]
    ns = sum(r["ok"] for r in within); nw = len(within)
    z, ph = 1.96, ns / max(nw, 1)
    lb = (ph + z * z / (2 * nw) - z * math.sqrt(ph * (1 - ph) / nw + z * z / (4 * nw * nw))) / (1 + z * z / nw) if nw else 0
    marg = [11.0 / r["peak"] for r in within if r["ok"]]
    L = ["# Threshold / carpet Monte Carlo (generated by `python -m rnd.threshold_mc`)", "", __doc__.split("\n\n", 1)[1].strip(), "",
         f"**Within the 15 mm design limit: {ns}/{nw} cross ({ph:.0%}; 95 % lower bound {lb:.0%}).** "
         f"Beyond it (15–18 mm): {sum(r['ok'] for r in beyond)}/{len(beyond)}.",
         f"Torque margin (11 N·m / peak) on successful ≤ 15 mm crossings: min {min(marg):.2f}×, median {np.median(marg):.2f}×." if marg else "", "",
         "| h (mm) | Heading (°) | v (m/s) | Floor | μ × | Mass (kg) | COM (m) | Result | Peak τ (N·m) | Max tilt (°) |", "|---|---|---|---|---|---|---|---|---|---|"]
    L += [f"| {r['h'] * 1000:.1f} | {r['head']:.0f} | {r['v']:.2f} | {'carpet' if r['carpet'] else 'hard'} | {r['mu']:.2f} | {r['mass']:.1f} | {r['com']:.2f} | "
          f"{'✅' if r['ok'] else '❌'} | {r['peak']:.1f} | {r['tilt']:.1f} |" for r in sorted(rows, key=lambda r: r["h"])]
    (DOCS / "threshold_mc.md").write_text("\n".join(L))
    (DOCS / "threshold_mc.json").write_text(json.dumps({"n": nw, "ok": ns, "lb95": lb, "beyond_ok": sum(r["ok"] for r in beyond),
                                                       "beyond_n": len(beyond), "margin_min": min(marg) if marg else 0}))
    print("\n".join(L[4:6]))


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 80)
