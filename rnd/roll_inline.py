"""D24 inline shoulder roll (GIM8108-36) vs the belt roll: the checks for both drives, side by side.

    python -m rnd.roll_inline dome                              # belt dome (the default drive)
    PIP_ROLL_DRIVE=inline python -m rnd.roll_inline <check>     # check ∈ dome, assembly_seq, spacing, swept, dexterity, basket

The CAD and the twin read params.ROLL_DRIVE at import, so each drive is a separate run. Results go to
docs/rnd/roll_inline.json (one entry per drive and check) and docs/rnd/roll_inline.md; the baseline reports
(assembly_seq.md, swept.md, ...) are not touched. Run one heavy check at a time.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "docs" / "rnd"
JS = DOCS / "roll_inline.json"
EST = dict(belt=(172, 210), inline=(128, 120))      # slim_study.ENVELOPE shoulder dome w × h, ESTIMATE (V0 / V2)


def check(name):
    from .params import BASELINE
    drive = BASELINE.arm.roll_drive
    if name == "dome":
        from .parts import roll
        d = roll.dome()
        return dict(**d, roll_y=roll.ROLL_Y, yaw_drop=roll.YAW_DROP, masses=[round(m, 3) for m in roll.masses(split=True)],
                    ferrule_gap=round(roll.ferrule_sweep_gap(roll.ROLL_Y), 2) if drive == "inline" else None, est=EST[drive])
    if name == "assembly_seq":
        from . import assembly_seq
        rows = assembly_seq.run()
        return dict(ok=sum(r["ok"] for r in rows), n=len(rows), roll=[dict(name=r["name"], ok=r["ok"], bearings=r["bearings"]) for r in rows if r["name"].startswith("roll")])
    if name == "spacing":
        import itertools
        from .parts import roll
        from .spacing import RULES, classify
        rows = []                                    # rnd/spacing.py run(), roll/yaw module only
        for (a, pa, _), (b, pb, _) in itertools.combinations(roll.module(), 2):
            ba, bb = pa.bounding_box(), pb.bounding_box()
            if (ba.min.X > bb.max.X + 2 or bb.min.X > ba.max.X + 2 or ba.min.Y > bb.max.Y + 2 or bb.min.Y > ba.max.Y + 2
                    or ba.min.Z > bb.max.Z + 2 or bb.min.Z > ba.max.Z + 2):
                continue
            k = classify(a, b)
            if k == "mate":
                continue
            dist = pa.distance_to(pb)
            tgt, hard = RULES[k]
            if dist < tgt:
                rows.append(dict(a=a, b=b, kind=k, d=round(dist, 2), target=tgt, hard=hard, hard_fail=dist < hard))
        return dict(under_target=len(rows), under_hard=sum(r["hard_fail"] for r in rows), rows=rows)
    if name == "swept":
        from . import swept
        from .spacing import RULES, classify
        res = swept.run()
        bad = []
        for j, w in res.items():
            for (a, b), (d, t) in w.items():
                k = classify(a, b)
                tgt, hard = (swept.TARGET, swept.HARD) if k in ("static", "mate") else RULES[k]
                if d < tgt - 0.005:
                    bad.append(dict(joint=j, a=a, b=b, kind=k, d=round(d, 2), at=t, target=tgt, hard=hard))
        mins = {j: round(min((v[0] for v in w.values()), default=99), 2) for j, w in res.items()}
        closest = {j: sorted(((round(d, 2), a, b, t) for (a, b), (d, t) in w.items()))[:4] for j, w in res.items()}
        return dict(min=mins, under_target=len(bad), under_hard=sum(r["d"] < r["hard"] for r in bad), rows=bad, closest=closest)
    if name == "dexterity":
        from . import dexterity
        r = dexterity.run()
        return dict(**r, ok=all(r[k] >= dexterity.TARGETS[k] for k in dexterity.TARGETS))
    if name == "basket":
        from . import basket
        rows, cap = basket.run()
        sel = [r for r in rows if r["x"] <= 0.45 and "washer" not in r["pose"] and "0.80" not in r["pose"]]
        ok = all(r["t"] is not None and r["worst"] >= 1.0 and r["tip_wheel"] >= 0.03 for r in sel)
        return dict(ok=ok, worst=round(min((r["worst"] for r in sel if r["t"] is not None), default=0), 2),
                    roll_peak_margin=round(min((r["use"]["roll"] for r in sel if r["t"] is not None), default=0), 2),
                    no_ik=sum(r["t"] is None for r in sel), cap={j: [round(x, 1) for x in c[2:4]] for j, c in cap.items()})
    raise SystemExit(f"unknown check {name}")


def report(res):
    L = ["# D24 inline shoulder roll vs the belt roll (generated by `python -m rnd.roll_inline`)", "", __doc__.split("\n\n", 1)[1].strip(), "",
         "| Check | belt (GIM6010-8 + 18T:80T) | inline (GIM8108-36) |", "|---|---|---|"]
    g = lambda d, c: res.get(d, {}).get(c)

    def row(label, c, f):
        L.append(f"| {label} | " + " | ".join((f(g(d, c)) if g(d, c) is not None else "not run") for d in ("belt", "inline")) + " |")
    row("Shoulder dome, fore-aft × height (mm), CAD", "dome", lambda r: f"{r['width_x']:.0f} × {r['height_z']:.0f} (slim-study ESTIMATE {r['est'][0]} × {r['est'][1]})")
    row("Dome reach outboard of the detach plane (mm)", "dome", lambda r: f"{r['out_y']:.0f}")
    row("ROLL_Y / yaw_drop (mm)", "dome", lambda r: f"{r['roll_y']:.1f} / {r['yaw_drop']:.1f}")
    row("Roll / yaw stage mass, CAD (kg, actuator not included)", "dome", lambda r: f"{r['masses'][0]:.2f} / {r['masses'][1]:.2f}")
    row("R14 assembly sequence, roll row", "assembly_seq", lambda r: ("✅" if all(x["ok"] for x in r["roll"]) else "❌") + f" ({r['ok']}/{r['n']} shafts)")
    row("R15 spacing, roll/yaw module (under target / hard)", "spacing", lambda r: f"{r['under_target']} / {r['under_hard']} {'✅' if r['under_hard'] == 0 else '❌'}")
    row("R15 swept: min gap roll / yaw (mm); pairs under target / hard", "swept",
        lambda r: f"{r['min']['roll']:.1f} / {r['min']['yaw']:.1f}; {r['under_target']} / {r['under_hard']} {'✅' if r['under_target'] == 0 else '❌'}")
    row("R16 dexterity: top-down / 45° / side / across", "dexterity",
        lambda r: " / ".join(f"{r[k]:.0%}" for k in ("top-down", "45° angled", "side (horizontal)", "side, across the body")) + (" ✅" if r["ok"] else " ❌"))
    row("R2d basket: worst duty margin; roll peak margin", "basket", lambda r: f"{r['worst']:.2f}; {r['roll_peak_margin']:.1f}× {'✅' if r['ok'] else '❌'}")
    for d in ("belt", "inline"):
        s = g(d, "swept")
        if s and s["rows"]:
            L += ["", f"Swept pairs under target ({d}):", ""] + [f"- {r['joint']}: {r['a']} ↔ {r['b']} ({r['kind']}) {r['d']} mm at {r['at']}°" for r in s["rows"]]
        s = g(d, "spacing")
        if s and s["rows"]:
            L += ["", f"Spacing pairs under target ({d}):", ""] + [f"- {r['a']} ↔ {r['b']} ({r['kind']}) {r['d']} mm (target {r['target']})" for r in s["rows"]]
    (DOCS / "roll_inline.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[4:]))


def main():
    from .params import BASELINE
    drive = BASELINE.arm.roll_drive
    res = json.loads(JS.read_text()) if JS.exists() else {}
    for name in sys.argv[1:] or ["dome"]:
        r = check(name)
        res.setdefault(drive, {})[name] = r
        print(drive, name, json.dumps(r, default=str)[:600], flush=True)
        JS.write_text(json.dumps(res, indent=1, default=str))
    report(res)


if __name__ == "__main__":
    main()
