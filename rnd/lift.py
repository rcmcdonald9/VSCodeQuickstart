"""Lift study (queue #5): how the torso carriage rides the spine and holds when power is off.

Moving mass = everything above the carriage (torso, head, compute, both shoulder modules, both arms, cables) + payload.
Options compared on mass, cost, speed, power-off behaviour, holding power and carry mode.
"""
from __future__ import annotations

import math

from .belts import B as BELT, pd
from .budget import mass_budget
from .params import BASELINE, Design, act, G

TRAVEL = None   # from params
ACCEL = 1.0     # m/s² carriage acceleration (ESTIMATE, brisk)
PAYLOAD = 2.0   # kg, both hands


def moving_mass(d: Design = BASELINE) -> float:
    mb = mass_budget(d)
    fixed = {"spine extrusion", "lift motor", "handle", "coupling (upper half)"} | ({"head"} if d.upper.head_on_mast else set())
    upper = sum(m for n, m in mb["upper"] if n not in fixed)
    arms = 2 * sum(m for _, m in mb.get("arm (each, detachable)", []))
    return upper + arms


OPTIONS = {
    "A: NEMA23 2 N·m + 24 V brake, GT2 belt (v0 placeholder)": dict(
        mass=1.25, cost=75, speed=0.25, hold="spring-applied brake (fail-safe)", hold_w=4.5,
        risk="heaviest; another motor type + driver to stock", reusable=False),
    "B: constant-force springs + NEMA17": dict(
        mass=0.60, cost=80, speed=0.30, hold="springs balance; drifts with payload; needs a brake anyway",
        hold_w=0, risk="springs shoot the carriage up when the arms come off (carry mode); CF-spring fatigue 2.5k–25k cycles", reusable=False),
    "C: GIM6010-8 cartridge + HTD 5M belt + spring-applied ratchet pawl (solenoid release)": dict(
        mass=0.55, cost=95, speed=0.20, hold="pawl drops into the ratchet whenever power is off (fail-safe); 0 W at rest",
        hold_w=0, risk="clicks if the pawl isn't held off while rising; height stops are 5 mm-quantised when parked", reusable=True),
    "D: self-locking lead screw Tr12×3 + NEMA17": dict(
        mass=0.70, cost=60, speed=0.03, hold="self-locking screw", hold_w=0,
        risk="0.7 m of travel takes ~23 s; long screw whips", reusable=False),
}
CHOICE = "C: GIM6010-8 cartridge + HTD 5M belt + spring-applied ratchet pawl (solenoid release)"


def option_c(d: Design = BASELINE):
    M = moving_mass(d) + PAYLOAD
    F = M * (G + ACCEL)
    r = pd(20) / 2 / 1000
    gim = act("GIM6010-8")
    torque = F * r
    v_rated = gim["speed"] * r                    # rated speed (rad/s) × radius
    travel = d.upper.lift_max - d.upper.lift_min
    allow = BELT["allowable_tension_n_per_10mm"] * 15 / 10
    pawl_shock = 3 * M * G                       # pawl catch after a power loss mid-move (ESTIMATE ×3)
    tooth_shear = pawl_shock / (15 * 3.0)        # MPa, 15 mm wide × 3 mm tooth root in PETG
    return dict(M=M, F=F, torque=torque, m_torque=gim["rated"] / torque, v=v_rated, t_full=travel / v_rated,
                belt_sf=allow / F, tooth_shear=tooth_shear)


def report(d: Design = BASELINE) -> str:
    c = option_c(d)
    L = ["# Lift (auto-generated by `python -m rnd.run_all`)", "",
         f"Moving mass {c['M'] - PAYLOAD:.1f} kg + {PAYLOAD:.0f} kg payload; travel {d.upper.lift_min}–{d.upper.lift_max} m; accel {ACCEL} m/s².", "",
         "| Option | Mass (kg) | Cost ($, ESTIMATE) | Speed (m/s) | Power-off | Holding power | Main risk |", "|---|---|---|---|---|---|---|"]
    for n, o in OPTIONS.items():
        star = " **← chosen**" if n == CHOICE else ""
        L.append(f"| {n}{star} | {o['mass']:.2f} | {o['cost']} | {o['speed']:.2f} | {o['hold']} | {o['hold_w']} W | {o['risk']} |")
    L += ["", "## Option C numbers", "", "| Check | Value |", "|---|---|",
          f"| Force (moving + payload, with accel) | {c['F']:.0f} N |",
          f"| Motor torque on a 20T HTD 5M pulley | {c['torque']:.2f} N·m → **{c['m_torque']:.2f}×** rated margin |",
          f"| Speed at rated rpm / full travel | {c['v']:.2f} m/s / {c['t_full']:.1f} s (faster when lightly loaded, up to ~420 rpm) |",
          f"| Belt (15 mm HTD 5M, open-ended along the spine) | safety {c['belt_sf']:.1f}× |",
          f"| Pawl catch after a power loss mid-move (×3 shock) | ratchet tooth shear {c['tooth_shear']:.1f} MPa in PETG (limit ~30) |", "",
          "**Why C:** it's the lightest and uses the standard GIM cartridge (motors are reusable across builds). It holds with **zero power** at rest, "
          "and it's fail-safe: the pawl is spring-applied and solenoid-released, so losing power drops it into the ratchet. "
          "Precedent: spring-applied / power-released safety brakes and ratchet fall arrest (stair lifts, hoists, FRC climbers).",
          "**Carry mode:** park at the lowest stop with the pawl engaged; nothing is spring-loaded, so removing the arms is safe (unlike B).",
          "**Lowering sequence:** lift 2 mm to unload the pawl → solenoid retracts it → move → solenoid off → settle onto the next tooth."]
    return "\n".join(L)


def score(d: Design = BASELINE):
    c = option_c(d)
    return c["m_torque"], c["t_full"]


if __name__ == "__main__":
    print(report())
