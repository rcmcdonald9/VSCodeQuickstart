"""Static + dynamic joint torque sizing for the 6-DOF arm (T05).

Worst gravity case for the pitch joints is the arm held horizontal. The
'spec' case is R2: 1 kg payload at 0.45 m horizontal reach from the shoulder.
Required torque is compared with each cartridge's rated (continuous) and peak
torque after its in-bone reduction (belt efficiency 0.95).
"""
from __future__ import annotations

import math

from .params import BASELINE, Design, act, G

BELT_EFF = 0.95
ALPHA = 6.0          # rad/s² joint acceleration for the dynamic check (ESTIMATE: brisk, human-like)


def point_masses(d: Design, reach: float | None = None):
    """(name, mass, x from shoulder pitch axis) for a straight horizontal arm.
    If reach is given, the arm is shortened proportionally so the grasp point sits at `reach`."""
    a = d.arm
    m = {j: act(n)["mass"] for j, (n, _) in a.joints.items()}
    L = a.l_upper + a.l_fore + a.l_hand
    s = 1.0 if reach is None else reach / L
    lu, lf = a.l_upper * s, a.l_fore * s
    pts = [("shoulder_roll", m["shoulder_roll"], 0.05 * s), ("upper_yaw", m["upper_yaw"], 0.12 * s),
           ("upper bone", a.bone_mass_upper, 0.5 * lu),
           *((("elbow", m["elbow"], lu),) if a.elbow_motor_at is None else
             (("elbow motor (remote)", m["elbow"], a.elbow_motor_at * s), ("elbow hub", a.elbow_hub_mass, lu))),
           ("fore bone", a.bone_mass_fore, lu + 0.5 * lf), ("wrist_pitch", m["wrist_pitch"], lu + lf),
           ("wrist_roll", m["wrist_roll"], lu + lf + 0.04 * s),
           ("gripper", m["gripper"] + a.gripper_mech_mass + a.wrist_cam_mass, lu + lf + 0.08 * s),
           ("payload", a.payload, lu + lf + a.l_hand * s)]
    return pts, {"shoulder_pitch": 0.0, "elbow": lu, "wrist_pitch": lu + lf}


def joint_loads(d: Design, reach=None):
    pts, axes = point_masses(d, reach)
    out = {}
    for j, x0 in axes.items():
        outboard = [(n, m, x - x0) for n, m, x in pts if x > x0 + 1e-9]
        grav_self = sum(m * G * r for n, m, r in outboard if n != "payload")
        grav_pay = sum(m * G * r for n, m, r in outboard if n == "payload")
        inertia = sum(m * r * r for n, m, r in outboard)
        if j == "shoulder_pitch":
            grav_self *= (1 - d.arm.spring_assist)
        out[j] = {"static": grav_self + grav_pay, "dynamic": grav_self + grav_pay + inertia * ALPHA}
    # shoulder roll with the arm held out sideways = same gravity moment, no spring help
    sp = joint_loads_raw(pts)
    out["shoulder_roll"] = {"static": sp, "dynamic": sp + out["shoulder_pitch"]["dynamic"] - out["shoulder_pitch"]["static"]}
    return out


def joint_loads_raw(pts):
    return sum(m * G * x for n, m, x in pts)


def capacity(d: Design, joint: str):
    name, ratio = d.arm.joints[joint]
    a = act(name)
    eff = BELT_EFF if ratio != 1.0 else 1.0
    return name, ratio, a["rated"] * ratio * eff, a["peak"] * ratio * eff, a["speed"] / ratio


def report(d: Design = BASELINE) -> str:
    L = ["# Arm sizing (auto-generated by `python -m rnd.run_all`)", "",
         f"Arm {d.arm.l_upper:.2f} + {d.arm.l_fore:.2f} + {d.arm.l_hand:.2f} m, payload {d.arm.payload} kg, "
         f"shoulder spring cancels {d.arm.spring_assist:.0%} of the arm's own weight, dynamic check at {ALPHA} rad/s².", ""]
    for title, reach in (("Worst case: arm straight out horizontally, full reach", None),
                         ("Spec case R2: payload at 0.45 m horizontal reach", 0.45)):
        loads = joint_loads(d, reach)
        L += [f"## {title}", "", "| Joint | Cartridge × ratio | Need static / dynamic (N·m) | Rated / peak available | Margin rated (static) | Margin peak (dynamic) | Joint speed (rad/s) |",
              "|---|---|---|---|---|---|---|"]
        for j in ("shoulder_pitch", "shoulder_roll", "elbow", "wrist_pitch"):
            name, ratio, rated, peak, spd = capacity(d, j)
            st, dy = loads[j]["static"], loads[j]["dynamic"]
            mr, mp = rated / st, peak / dy
            flag = "✅" if mr >= 1.5 and mp >= 1.5 else ("⚠️" if mr >= 1.0 and mp >= 1.0 else "❌")
            L.append(f"| {j} | {name} × {ratio:g} | {st:.2f} / {dy:.2f} | {rated:.1f} / {peak:.1f} | {mr:.2f} | {mp:.2f} {flag} | {spd:.1f} |")
        L.append("")
    g_force = d.arm.payload * G / (2 * 0.5) * 2
    L += ["## Gripper", "", f"Holding {d.arm.payload} kg with friction 0.5 on two fingers, safety ×2 → **{g_force:.0f} N** grip.",
          f"STS3215 (0.98 N·m rated) on a 10 mm pinion gives ≈ {0.98/0.01:.0f} N → ✅.", "",
          "✅ ≥ 1.5× margin on both, ⚠️ ≥ 1.0×, ❌ < 1.0×. The worst case (full horizontal reach with 1 kg) is beyond the R2 spec; it shows how the arm degrades."]
    return "\n".join(L)
