"""Mass, cost-of-actuators and power budget (T02)."""
from __future__ import annotations

from .params import BASELINE, Design, act


def arm_items(d: Design):
    a = d.arm
    items = []
    for j, (name, _) in a.joints.items():
        items.append((f"arm {j}", act(name)["mass"]))
    items += [("arm bones+shells", a.bone_mass_upper + a.bone_mass_fore),
              ("gripper mechanism", a.gripper_mech_mass), ("wrist camera", a.wrist_cam_mass)]
    if a.elbow_motor_at is not None:
        items.append(("elbow pulley hub (remote motor)", a.elbow_hub_mass))
    return items


def mass_budget(d: Design = BASELINE):
    b, u, a_ = d.base, d.upper, d.arm
    nwheel = 3 if b.layout == "kiwi" else 4
    wheel_kg = 0.45
    base = [("wheel cartridges", nwheel * act(b.wheel_motor)["mass"]), ("omni wheels", nwheel * wheel_kg),
            ("chassis", b.struct_mass), ("shell", b.shell_mass), ("electronics", b.electronics_mass),
            ("lidar", b.lidar_mass), ("coupling (base half)", b.coupling_mass / 2)]
    arms = arm_items(d)
    upper = [("spine extrusion", u.spine_len * u.spine_mass_per_m), ("lift motor", u.lift_motor_mass),
             ("carriage", u.carriage_mass), ("torso", u.torso_struct_mass), ("compute", u.compute_mass),
             ("head", u.head_mass), ("cables", u.cable_mass), ("handle", u.handle_mass),
             ("coupling (upper half)", b.coupling_mass / 2)]
    upper += [("2× shoulder pitch stage + spring", 2 * (a_.shoulder_stage_mass + a_.spring_module_mass)),
              ("2× arm shoulder_pitch", 2 * act(a_.joints["shoulder_pitch"][0])["mass"])]
    arm_piece = [(n, m) for n, m in arms if n != "arm shoulder_pitch"] + [("roll stage", a_.shoulder_stage_mass)]
    out = {"base": base, "battery": [("6S pack", b.battery_mass)]}
    if u.arms_detach:
        out["upper"] = upper
        out["arm (each, detachable)"] = arm_piece
    else:
        out["upper"] = upper + [(f"2× {n}", 2 * m) for n, m in arm_piece]
    return out


def upper_total(mb):
    """Assembled upper module (core + both arms), for the twin and the drive."""
    return sum(m for _, m in mb["upper"]) + 2 * sum(m for _, m in mb.get("arm (each, detachable)", []))


def actuator_cost(d: Design = BASELINE):
    names = [n for n, _ in d.arm.joints.values()] * 2
    names += [d.base.wheel_motor] * (3 if d.base.layout == "kiwi" else 4)
    names += ["STS3215-C018"] * 2   # head pan/tilt
    return sum(act(n)["price"] for n in names), len(names)


def power_budget(d: Design = BASELINE):
    """Average electrical power per mode (W). ESTIMATES until Phase-1 measurements."""
    electronics = 5 + 3 + 1.5 + 1 + 3   # Pi 5, cameras, lidar, display, CAN/DC-DC losses
    servo_idle = 10 * 0.6               # STS + Damiao idle electronics (ESTIMATE)
    gim_idle = 9 * 0.8                  # GIM SDC104 idle (ESTIMATE)
    modes = {
        "standby (arms parked, base still)": electronics + servo_idle + gim_idle,
        "manipulating (arms holding/moving light objects)": electronics + servo_idle + gim_idle + 45,
        "driving on carpet + arms parked": electronics + servo_idle + gim_idle + 30,
    }
    duty = {"standby (arms parked, base still)": 0.5, "manipulating (arms holding/moving light objects)": 0.35,
            "driving on carpet + arms parked": 0.15}
    avg = sum(modes[m] * duty[m] for m in modes)
    return modes, duty, avg, d.base.battery_wh * 0.85 / avg


def report(d: Design = BASELINE) -> str:
    mb = mass_budget(d)
    tot = {k: sum(m for _, m in v) for k, v in mb.items()}
    cost, n = actuator_cost(d)
    modes, duty, avg, hours = power_budget(d)
    L = ["# Mass and power budget (auto-generated by `python -m rnd.run_all`)", "",
         "| Module | Mass (kg) | Target (R3) | Status |", "|---|---|---|---|"]
    targets = {"upper": 10, "base": 6, "battery": 3, "arm (each, detachable)": 10}
    for k in mb:
        L.append(f"| {k} | {tot[k]:.2f} | ≤ {targets[k]} | {'✅' if tot[k] <= targets[k] else '❌'} |")
    narm = 2 if "arm (each, detachable)" in mb else 0
    L.append(f"| **total robot** | **{sum(tot.values()) + (narm - 1) * tot.get('arm (each, detachable)', 0) if narm else sum(tot.values()):.2f}** | | |")
    for k in [k for k in mb if k != "battery"]:
        L += ["", f"**{k} detail**", "", "| Item | kg |", "|---|---|"]
        L += [f"| {n} | {m:.3f} |" for n, m in sorted(mb[k], key=lambda x: -x[1])]
    L += ["", f"**Actuators:** {n} joints, ≈ **${cost:,.0f}** at mid list price.", "",
          "## Power (ESTIMATES until Phase-1 measurement)", "", "| Mode | W | Share of time |", "|---|---|---|"]
    L += [f"| {m} | {w:.0f} | {duty[m]:.0%} |" for m, w in modes.items()]
    L += [f"| **weighted average** | **{avg:.0f}** | |", "",
          f"Runtime on {d.base.battery_wh:.0f} Wh (85 % usable): **{hours:.1f} h** (R7 target 2 h, limit 1 h)."]
    return "\n".join(L)
