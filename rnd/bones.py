"""Bone strength and stiffness: printed shells under the worst static load ×1.5 (arm straight out, 1 kg payload).

Sections (from rnd/parts/arm.py): upper-arm neck (round tube), elbow housing (rounded box), forearm side link (box).
Checks: peak bending stress vs printed-PETG allowable (layer-adhesion-limited), and the hand's vertical deflection
from bone bending alone (joint/belt compliance is separate and not yet modelled).
"""
from __future__ import annotations

import math

import numpy as np

from .arm_sizing import point_masses
from .params import BASELINE, Design, G

E_PRINTED = 1.8e3          # MPa, printed PETG along the walls (ESTIMATE: ~85 % of the filament modulus)
E_CF = 70e3                # MPa, roll-wrapped carbon tube, axial (ESTIMATE; catalogue 60–110 GPa)
CF_ALLOW = 150.0           # MPa, CF tube bending allowable with safety (ESTIMATE; typical strength 600+)
CF_KG_PER_M = {30: 0.14, 40: 0.19}   # Ø×1 mm wall roll-wrapped tube, kg/m (ESTIMATE: area × 1.55 g/cm³)
ALLOW = 12.0               # MPa: 50 MPa filament × 0.5 layer adhesion / SF 2 (ESTIMATE)
DYN = 1.5
DEFLECTION_TARGET = 2.0    # mm at the hand from bone bending (ESTIMATE target: fine manipulation is closed-loop on the wrist camera)


def tube(od, t):
    ri, ro = od / 2 - t, od / 2
    return math.pi / 4 * (ro ** 4 - ri ** 4), ro                      # I (mm⁴), extreme fibre (mm)


def box(b, h, t):
    """b across the bending axis, h in the bending plane (depth)."""
    return (b * h ** 3 - (b - 2 * t) * (h - 2 * t) ** 3) / 12, h / 2


def segments(wall: float, d: Design = BASELINE, cf: bool = False):
    """(name, x0, x1 from the shoulder pitch axis in m, I mm⁴, c mm, E MPa). Arm straight and horizontal (worst case).
    cf=True: the neck and the forearm link become carbon tubes (Ø40×1 and Ø30×1) bonded into printed end fittings."""
    yaw_at, lu = 0.07, d.arm.l_upper
    neck = ("upper-arm neck CF Ø40×1", *tube(40, 1.0), E_CF) if cf else ("upper-arm neck Ø72 printed", *tube(72, wall), E_PRINTED)
    fore = ("forearm CF Ø30×1", *tube(30, 1.0), E_CF) if cf else ("forearm side link 22×56 printed", *box(22, 56, wall), E_PRINTED)
    return [("roll link (pitch → yaw)", 0.0, yaw_at, *box(90, 90, max(wall, 2.0)), E_PRINTED),
            (neck[0], yaw_at, yaw_at + 0.10, *neck[1:]),
            ("elbow housing 98×108", yaw_at + 0.10, lu, *box(108, 98, wall), E_PRINTED),
            (fore[0], lu, lu + d.arm.l_fore, *fore[1:])]


def analyse(wall: float, d: Design = BASELINE, cf: bool = False):
    pts, _ = point_masses(d)
    xs = np.linspace(0, d.arm.l_upper + d.arm.l_fore, 400)
    M = np.array([sum(m * G * (x - xp) for _, m, x in pts if x > xp) for xp in xs]) * DYN   # N·m
    segs = segments(wall, d, cf)
    EI = np.empty_like(xs)
    out = []
    for name, x0, x1, I, c, E in segs:
        sel = (xs >= x0) & (xs <= x1)
        EI[sel] = E * I * 1e-6                           # N·m² (MPa·mm⁴ → N·m²: ×1e-6)
        sigma = (M[sel].max() * 1000) * c / I            # MPa
        out.append(dict(name=name, sigma=sigma, I=I, allow=CF_ALLOW if E == E_CF else ALLOW))
    # tip deflection: integrate curvature M/EI twice along the arm (cantilever from the pitch axis)
    kappa = M / EI
    slope = np.concatenate([[0], np.cumsum((kappa[1:] + kappa[:-1]) / 2 * np.diff(xs))])
    defl = np.concatenate([[0], np.cumsum((slope[1:] + slope[:-1]) / 2 * np.diff(xs))])
    # the hand segment beyond the wrist is short and stiff: extend with the wrist slope
    tip = defl[-1] + slope[-1] * d.arm.l_hand
    return out, tip * 1000 / DYN                          # deflection reported at the static (×1) load


def report(d: Design = BASELINE) -> str:
    L = ["# Bones: strength and stiffness (auto-generated by `python -m rnd.run_all`)", "",
         f"Arm straight out horizontally with {d.arm.payload} kg (the worst static case), loads ×{DYN} for dynamics. "
         f"Printed PETG: E ≈ {E_PRINTED / 1000:.1f} GPa, allowable {ALLOW:.0f} MPa (layer adhesion ×0.5, safety 2). "
         "Deflection is from bone bending only (belt and bearing compliance are not included yet).", "",
         "| Wall | Peak stress per segment (MPa) | Hand deflection, static |", "|---|---|---|"]
    for cf in (False, True):
        for w in ((2.4, 1.6, 1.2) if not cf else (1.6, 1.2)):
            segs, tip = analyse(w, d, cf)
            ok = all(s["sigma"] <= s["allow"] for s in segs)
            txt = "; ".join(f"{s['name']}: {s['sigma']:.1f}" for s in segs)
            tag = f"{w} mm printed" + (" + **CF tubes**" if cf else "")
            L.append(f"| {tag} | {txt} {'✅' if ok else '❌'} | {tip:.2f} mm {'✅' if tip <= DEFLECTION_TARGET else '⚠️'} |")
    L += ["", "**Reading:** printed shells are strong enough at any practical wall thickness, but **stiffness** limits them: "
          "even 2.4 mm walls let the hand sag ~3 mm. Thinner walls save mass but make it worse. Carbon tubes for the two slender sections "
          "(precedent: Hello Robot Stretch's carbon-tube arm, Kinova's carbon links) are ~40× stiffer per section than printed PETG, and they're lighter.",
          "Belt stretch and bearing play add further compliance; that goes in twin v1 (dynamic)."]
    return "\n".join(L)


def score(d: Design = BASELINE):
    segs, tip = analyse(d.arm.bone_wall_mm, d, d.arm.cf_tubes)
    return max(s["sigma"] / s["allow"] for s in segs), tip


if __name__ == "__main__":
    print(report())
