"""M1 purchase readiness: what the bench-arm buy depends on, and how sure each answer is.  python -m rnd.m1_readiness

Reads the cached results of the checks (docs/rnd/*.json) so the numbers in the report are the ones the checks produced.
"""
from __future__ import annotations

import json
from pathlib import Path

D = Path(__file__).resolve().parent.parent / "docs"
J = lambda n: json.loads((D / "rnd" / n).read_text()) if (D / "rnd" / n).exists() else {}


def main():
    from .m1_kit import items, CONTINGENCY
    from .params import BASELINE
    from .spring import workspace_margins
    wm = workspace_margins(BASELINE)
    sub = sum(q * u for _, _, q, u, _, _ in items())
    th, st, dx, sw, asq, integ, sp, kx, hn = (J("thermal.json"), J("stiffness.json"), J("dexterity.json"), J("swept.json"), J("assembly_seq.json"),
                                              J("integration.json"), J("spacing.json"), J("kx_mc.json"), J("harness.json"))
    mr = min(v["m_rated"] for v in wm.values())
    mp = min(v["m_peak"] for v in wm.values())
    rows = [
        ("Motors: 4 × GIM6010-8, 1 × DM-J4310, 2 × STS3215",
         f"whole-workspace margin ≥ {mr:.2f}× rated (p95, 1 kg), ≥ {mp:.2f}× peak; hottest winding {th.get('task_max_c', float('nan')):.0f} °C on a non-stop task day",
         "high (90 %)", "The only buy that is expensive to undo. Every joint passes with the loop-40 masses (heavier shoulder and housing included)."),
        ("Gear ratios (belts, pulleys)", "pitch 3.0, roll 4.44 (80T), yaw 2.0, elbow 2.0; belt pull ≥ 1.5× working rating", "high (85 %)",
         "Pulleys are cheap to change later; the motors don't depend on them."),
        ("D13 drive parts (Ø12 shafts, couplings, aluminium pulleys, 6801s)", f"R14: {asq.get('ok', '?')}/{asq.get('n', '?')} shafts assemble; torque pins {integ.get('torque_ok', '?')}/{integ.get('torque_n', '?')}",
         "medium-high (75 %)", "Dimensions are ESTIMATE until the parts are in hand (check bore 12 mm on the pulleys)."),
        ("Bearings (61808, 6708, 6801, 61804, U604)", "counted from the CAD (loop 40)", "high (90 %)", "Cheap; a 10-pack of each covers spares."),
        ("Twist-lock couplings (D15 hardware)", f"slip below rated {kx.get('worst_p_below_rated', 0):.2%}; below peak {kx.get('worst_p_below_peak', 0):.0%} after 10-year creep",
         "medium (70 %)", "Coupon C1 measures the real slip, twist and repeatability; springs come as an assortment."),
        ("Balancer (die spring, 2:1 tackle)", "fits the 135 mm cage at 35 % of L0 (limit 40 %)", "medium (70 %)", "Pick the catalogue rate ≥ 12 N/mm; K adjusts with the pulley slot."),
        ("Bench electronics (24 V PSU, regen clamp, e-stop, 2 × USB-CAN)", "A5 + A14 (electrical.md)", "high (85 %)",
         "The regen clamp is the one line that must not be skipped: the PSU can't absorb back-driven energy and the GIM is rated 28 V."),
        ("Cable routing (ribbon stock, slim USB, CSI camera)", f"{hn.get('ok', '?')}/{hn.get('n', '?')} joints cross their full range; yaw ±150°", "medium (65 %)",
         "Clock-spring life is untested: add coupon C11 (10k cycles)."),
        ("Printed structure (not bought, but it decides whether M1 meets its accuracy goal)",
         f"hand deflection {st.get('total_mm', float('nan')):.0f} mm raw, {st.get('after_mm', float('nan')):.1f} mm after a gravity model (P2 FEA chain)",
         "medium (60 %)", "Loop 40 found the shells far softer with P2 elements and stiffened them; the bench arm measures it. Doesn't change what to buy."),
        ("Dexterity", f"top-down {dx.get('top-down', 0):.0%}, 45° {dx.get('45° angled', 0):.0%}, side {dx.get('side (horizontal)', 0):.0%}, across the body {dx.get('side, across the body', 0):.0%}",
         "high (85 %)", "Yaw ±150° is back."),
        ("Spacing / swept clearances", f"static hard violations {sp.get('under_hard', '?')}; swept roll/yaw {sw.get('under_hard', '?')}; module clashes {integ.get('module_clashes', '?')}",
         "high (85 %)", ""),
    ]
    L = ["# M1 bench arm: purchase readiness (generated by `python -m rnd.m1_readiness`)", "",
         f"**Kit:** ${sub:,.0f} + {CONTINGENCY:.0%} contingency = **${sub * (1 + CONTINGENCY):,.0f}** ([M1_BENCH_ARM.md](M1_BENCH_ARM.md)).", "",
         "**Verdict: buy the motors and electronics now; buy the D13 drive parts and belts with them, checking the listed dimensions.** Nothing found "
         "in loop 40 changes the motor choice, and the design changes it did force (80T roll pulley, D13 shafts, D16 spindle, D15 springs, die "
         "spring, regen clamp, second CAN channel, ASA) are all in the kit list. What remains uncertain is printed-part behaviour (stiffness, "
         "coupling slip and creep, clock-spring life), and that is what M1 and the coupons are for.", "",
         "| What you're buying / relying on | Evidence (checks in this repo) | Confidence | Note |", "|---|---|---|---|"]
    L += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in rows]
    L += ["", "## What could still make the purchase wrong", "",
          "- **Wrong motor variant delivered** (48 V GIM listing, J4310 V1.2 vs V1.1, 7.4 V STS3215): check the listing against M1_BENCH_ARM.md before paying.",
          "- **The GIM6010 CAN protocol** couldn't be read here (the manual is blocked). If it had no impedance/torque mode, control would fall back "
          "to position mode with torque limits: workable for the bench, weaker for learning policies. Ask the seller for the protocol document.",
          "- **DM-J4310 output-bearing moment rating** (≈ 0.9 N·m dynamic at the wrist pitch): ask the seller.",
          "- **Printed parts:** if C1 shows KX slip under rated torque, or M1 shows hand sag far above the chain estimate, the fix is in printed "
          "parts and fasteners (stiffer shells, PETG-CF / ASA, bolted joints), not in the motors.", "",
          "## Before the motors arrive", "",
          "1. Owner's own reviews (Fable, Astra): packets in docs/review/ (`python -m rnd.review_packet`).",
          "2. Print coupons C1–C9 as soon as the P2S arrives (C1 is now the D15 screwed socket).",
          "3. Bench prep: build the regen clamp and e-stop board first; first power-up of each motor current-limited at 1 A."]
    (D / "M1_READINESS.md").write_text("\n".join(L))
    print("\n".join(L[:6]))


if __name__ == "__main__":
    main()
