"""Monte Carlo of the KX joint couplings: tolerances, friction, spring scatter and PETG creep (queue item 6, loop 29).
python -m rnd.kx_mc

Model (rnd/kx_check.py): slip torque = P·r_ball / tan β; preload P = k·c. The spring rate is k ≈ P_nom / 3 mm and the
compression is c ≈ 3 mm nominal (D15, loop 40: 6 coil springs; loops 29–39 used 1.5 mm). Each draw (all ESTIMATE until coupon C1 measures them):
- spring rate ×N(1, 0.07): coil-spring tolerance ±10 % at ~1.5σ
- compression error N(0, 0.07 mm): ±0.1 mm on each of the two printed seats (collar tooth, hub step)
- contact angle β = 20° + N(0, 1°): dowel-pin positions in printed holes, ball pocket depth
- PETG creep over 10 years in the preload loop. The elastic loop deflection is 0.06 mm at P_nom (the collar alone is
  0.03 mm by FEA, doubled for hub + lugs), the creep modulus ratio E(10 y)/E is U(0.45, 0.6) at room temperature, and the
  arm joints near a warm motor (task-day 55 °C, rnd/thermal.md) use U(0.30, 0.40)
- ramp friction μ U(0.12, 0.30), for the twist effort

Pass rules:
- slip torque ≥ the actuator's rated (continuous) torque in ≥ 99.9 % of draws. Below rated, the joint would slip in
  normal work.
- Slip below *peak* is reported. That is the designed overload-clutch behaviour, but a high rate means lost position on
  hard moves (the joint-side encoders detect it).
- Twist torque ≤ 3 N·m in ≥ 95 %.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

from . import kx_check
from .params import BASELINE

DOCS = Path(__file__).resolve().parent.parent / "docs" / "rnd"
N = 200_000
COMP = 3.0          # D15 (loop 40): spring compression at lock. Was 1.5 mm (a 1.2 mm wave stack); softer springs halve the creep loss


def run(n=N, seed=11):
    rng = np.random.default_rng(seed)
    rows = []
    for r in kx_check.interface_rows(BASELINE):
        kx = r["kx"]
        k = kx.preload_n / COMP * rng.normal(1, 0.07, n)
        c = COMP + rng.normal(0, 0.10, n)                            # D15: 6 coil springs, 3 mm installed compression
        warm = r["act"].startswith(("GIM", "DM"))                    # arm/base GIM + DM joints sit next to a working motor
        ratio = rng.uniform(0.30, 0.40, n) if warm else rng.uniform(0.45, 0.60, n)
        creep = 0.06 * (1 / ratio - 1)                               # extra loop deflection (mm) after 10 years
        P = np.clip(k * (c - creep), 0, None)
        beta = np.radians(20 + rng.normal(0, 1.0, n))
        slip = P * kx.r_ball / 1000 / np.tan(beta)
        mu = rng.uniform(0.12, 0.30, n)
        rr = (kx.od / 2 + kx.lug_reach / 2) / 1000
        twist = P * rr * np.tan(np.radians(kx.ramp_deg) + np.arctan(mu)) + P * kx_check.MU_THRUST * (kx.r_hub - 1) / 1000
        rows.append(dict(name=f"{kx.name} + {r['act']}", rated=r["rated"], peak=r["peak"], slip_nom=r["slip"],
                         p_below_rated=float(np.mean(slip < r["rated"])), p_below_peak=float(np.mean(slip < r["peak"])),
                         slip_p01=float(np.quantile(slip, 0.001)), preload_loss=float(np.mean(1 - P / kx.preload_n)),
                         twist_p95=float(np.quantile(twist, 0.95)), warm=warm))
    return rows


def main():
    rows = run()
    worst_rated = max(r["p_below_rated"] for r in rows)
    worst_twist = max(r["twist_p95"] for r in rows)
    L = ["# KX coupling Monte Carlo (generated by `python -m rnd.kx_mc`)", "", __doc__.split("\n\n", 1)[1].strip(), "",
         f"**Worst P(slip < rated) = {worst_rated:.3%}** (rule ≤ 0.1 %). **Worst 95th-percentile twist = {worst_twist:.1f} N·m** (rule ≤ 3).", "",
         "| Interface | Rated / peak (N·m) | Nominal slip | 0.1 % slip | Mean preload loss (10 y creep + tol.) | P(slip < rated) | P(slip < peak) | Twist p95 (N·m) |",
         "|---|---|---|---|---|---|---|---|"]
    L += [f"| {r['name']}{' (warm)' if r['warm'] else ''} | {r['rated']:.2f} / {r['peak']:.2f} | {r['slip_nom']:.1f} | {r['slip_p01']:.1f} | "
          f"{r['preload_loss']:.1%} | {r['p_below_rated']:.3%} | {r['p_below_peak']:.1%} | {r['twist_p95']:.1f} |" for r in rows]
    L += ["", "**Reading:** coupon C1 (print-in-place KX socket) measures the real slip torque, twist and re-seat repeatability. "
          "These replace the ESTIMATE spreads above."]
    (DOCS / "kx_mc.md").write_text("\n".join(L))
    (DOCS / "kx_mc.json").write_text(json.dumps({"worst_p_below_rated": worst_rated, "worst_twist_p95": worst_twist,
                                                 "worst_p_below_peak": max(r["p_below_peak"] for r in rows)}))
    print("\n".join(L[4:]))


if __name__ == "__main__":
    main()
