"""Drivetrain on carpet (T03): rolling resistance, thresholds, speed, acceleration limits."""
from __future__ import annotations

import math

from .budget import mass_budget
from .params import BASELINE, Design, act, G

CRR_CARPET = (0.05, 0.10)   # rolling-resistance coefficient, hard-tread omni on low/medium pile (ESTIMATE, measure!)
MU_CARPET = 0.6             # TPU roller traction on carpet (ESTIMATE)
BASE_GROUPS = ("base", "battery", "ballast (2 removable blocks)")   # A10 v2: the removable ballast rides on the wheels too


def step_force(w: float, r: float, h: float) -> float:
    """Horizontal force to push a wheel of radius r with load w up a step of height h."""
    return w * math.sqrt(2 * r * h - h * h) / (r - h)


def robot_mass(d: Design = BASELINE) -> float:
    from .budget import upper_total
    mb = mass_budget(d)
    return upper_total(mb) + sum(m for k in BASE_GROUPS for _, m in mb.get(k, [])) + d.arm.payload * 2


def threshold_torque_45(d: Design = BASELINE, h: float = 0.015) -> float:
    n = 4 if d.base.layout == "xdrive" else 3
    r = d.base.wheel_d / 2
    F = step_force(robot_mass(d) * G / n, r, h)
    return F / math.cos(math.radians(45)) * r


def report(d: Design = BASELINE) -> str:
    b = d.base
    mb = mass_budget(d)
    from .budget import upper_total
    mass = upper_total(mb) + sum(m for k in BASE_GROUPS for _, m in mb.get(k, [])) + d.arm.payload * 2
    W = mass * G
    n = 4 if b.layout == "xdrive" else 3
    r = b.wheel_d / 2
    mot = act(b.wheel_motor)
    w_wheel = W / n
    L = ["# Drivetrain on carpet (auto-generated by `python -m rnd.run_all`)", "",
         f"Robot + 2 kg payload = **{mass:.1f} kg**; {n} × 6\" omni wheels (r = {r*1000:.0f} mm) direct-driven by {b.wheel_motor} "
         f"({mot['rated']} N·m rated / {mot['peak']} N·m peak, {mot['speed']*60/2/math.pi:.0f} rpm rated). "
         "Layout: **4-wheel, one wheel pointing forward**, holonomic.", "",
         "## Rolling resistance", "", "| Carpet | Crr (ESTIMATE) | Total force | Torque per driven wheel | Power at 0.8 m/s |",
         "|---|---|---|---|---|"]
    for name, c in zip(("low pile", "medium pile"), CRR_CARPET):
        F = c * W
        L.append(f"| {name} | {c} | {F:.1f} N | {F/2*r:.2f} N·m (2 wheels driving forward) | {F*0.8:.0f} W |")
    L += ["", "## Thresholds (wheel load ≈ " + f"{w_wheel:.0f} N)", "",
          "| Step | Push needed per wheel | Torque if the wheel climbs head-on | Torque at 45° heading | vs 5 N·m rated |", "|---|---|---|---|---|"]
    for h in (0.005, 0.010, 0.015, 0.020):
        F = step_force(w_wheel, r, h)
        t0, t45 = F * r, F / math.cos(math.radians(45)) * r
        L.append(f"| {h*1000:.0f} mm | {F:.0f} N | {t0:.2f} N·m | {t45:.2f} N·m | {'✅' if t45 < mot['rated'] else ('⚠️ peak' if t45 < mot['peak'] else '❌')} |")
    v_fwd = mot["speed"] * r
    a_motor = n * mot["rated"] / r / mass
    L += ["", "**Catch:** a wheel rolling *sideways* meets the step with its small rollers (~25 mm, ESTIMATE). It can't climb more than a few mm on its own; the other wheels have to drag it over.",
          "**Rule for the planner:** cross thresholds at a **45° heading**, so every wheel uses its full diameter. That needs ≤ " + f"{threshold_torque_45(d):.1f}" + " N·m per wheel for 15 mm, within rating. "
          "**Must be bench-tested** (Phase-1 base test); fallback is 8\" dual-row omni wheels (bigger rollers).", "",
          "## Speed and acceleration", "",
          f"- Forward speed at rated motor speed: **{v_fwd:.2f} m/s** (2 side wheels drive straight); at 45° heading {v_fwd*math.cos(math.radians(45)):.2f} m/s. Max motor speed allows ~{act(b.wheel_motor)['speed']*0+ 420*2*math.pi/60*r:.1f} m/s. R6 (0.8 m/s) ✅",
          f"- Motor-limited acceleration: {a_motor:.1f} m/s². Traction-limited (μ ≈ {MU_CARPET}): {MU_CARPET*G:.1f} m/s².",
          "- **Stability-limited** (twin v0): 1.4–1.6 m/s² with the arm at full high reach. **Controller limits: 1.0 m/s² with arms parked, 0.5 m/s² while manipulating.**", "",
          "## Odometry on carpet", "",
          "Wheel counts are unreliable on carpet (rollers slip and sink), so position comes from:",
          "1. a **PAA5100JE optical-flow** sensor, 15–35 mm above the floor, in the base centre",
          "2. **IMU** yaw",
          "3. **RPLIDAR C1** scan matching",
          "4. wheel counts, used only as a weak prior",
          "",
          "All fused in an EKF. Bench test: sensor height vs pile depth."]
    return "\n".join(L)
