"""Tip-over cases the review asked for (A10, loop 40; external review finding 11).  python -m rnd.tip

Quasi-static zero-moment-point check on the twin's mass model (rnd/twin.py, CAD masses from params):
ZMP = COM_xy − (h_com / g)·a − F_push·h_push / (M g), in the direction of the load, against the x-drive support polygon
(wheel contacts at r = 0.21 m at 0/90/180/270°). The polygon is weakest at 45° between wheels: the edge is only
0.21·cos 45° = 0.148 m from the centre, against 0.21 m toward a wheel.

Cases (both arms straight out at shoulder height, lift mid-travel, holding the load between the hands):
- payload 1 kg (R12) and **2.5 kg two-handed** (box lift)
- load direction toward a wheel (0°) and **between wheels (45°)**
- **braking** from 0.8 m/s in 1.6 s (0.5 m/s², while carrying: the inertial force points the way the robot was going)
- **a human nudge**: 30 N horizontal at 1.0 m (a hand on the shoulder)

Target: ZMP margin ≥ 30 mm in every case (twin v1 dynamic rule); R12 keeps its 50 mm static rule.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

DOCS = Path(__file__).resolve().parent.parent / "docs" / "rnd"
G = 9.81
A_BRAKE, F_PUSH, H_PUSH = 0.5, 30.0, 1.0


def _com(payload):
    import mujoco
    from .params import BASELINE
    from .twin import build_xml
    m = mujoco.MjModel.from_xml_string(build_xml(BASELINE))
    d = mujoco.MjData(m)
    for side in ("r", "l"):
        for j, v in (("pitch", -90.0), ("roll", 0.0), ("yaw", 0.0), ("elbow", 0.0), ("wpitch", 0.0)):
            jid = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, f"{j}_{side}")
            if jid >= 0:
                d.qpos[m.jnt_qposadr[jid]] = math.radians(v)
    lid = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, "lift")
    if lid >= 0:
        d.qpos[m.jnt_qposadr[lid]] = 0.5 * (m.jnt_range[lid][0] + m.jnt_range[lid][1])
    for side in ("r", "l"):                                          # the model carries a 1 kg payload on the right hand only
        b = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_BODY, f"payload_{side}")
        m.body_mass[b] = 1e-4
    mujoco.mj_kinematics(m, d)
    w = m.body_mass[1:]                                              # every body except the world (the robot is the only tree)
    M0 = float(w.sum())
    c0 = (w[:, None] * d.xipos[1:]).sum(axis=0) / M0
    pr = d.site_xpos[mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_SITE, "grasp_r")].copy()
    pl = d.site_xpos[mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_SITE, "grasp_l")].copy()
    base = np.zeros(3)
    p = 0.5 * (pr + pl)
    M = M0 + payload
    c = (c0 * M0 + p * payload) / M
    return M, c - base, p - base


CASTER_R = 0.22     # D18 (loop 40): 4 spring-loaded ball-transfer casters at the diagonals under the skirt edge


def polygon(casters):
    from .twin import support_polygon
    if not casters:
        return support_polygon("xdrive", 0.21, 0)
    pts = []
    for i in range(8):
        r = 0.21 if i % 2 == 0 else CASTER_R
        a = math.radians(45 * i)
        pts.append([r * math.cos(a), r * math.sin(a)])
    return np.array(pts)


def run(casters=False):
    from .twin import margin
    poly = polygon(casters)
    rows = []
    for payload in (1.0, 2.5):
        M, c, p = _com(payload)
        reach = math.hypot(c[0], c[1])
        for az in (0.0, 45.0):
            u = np.array([math.cos(math.radians(az)), math.sin(math.radians(az))])
            for brake, push in ((False, False), (True, False), (False, True), (True, True)):
                z = reach * u
                z = z + (c[2] / G * A_BRAKE * u if brake else 0) + (F_PUSH * H_PUSH / (M * G) * u if push else 0)
                rows.append(dict(payload=payload, az=az, brake=brake, push=push, M=M, h=c[2], com=reach, zmp=float(np.linalg.norm(z)),
                                 margin=float(margin(poly, z))))
    return rows


def main():
    rows0 = run(False)
    rows = run(True)
    worst0 = min(r["margin"] for r in rows0)
    worst = min(r["margin"] for r in rows)
    L = ["# Tip-over: review cases (generated by `python -m rnd.tip`)", "", __doc__.split("\n\n", 1)[1].strip(), "",
         f"**Worst ZMP margin: wheels only {worst0 * 1000:.0f} mm; with the D18 anti-tip casters {worst * 1000:.0f} mm** (rule ≥ 30 mm). "
         f"Mass {rows[0]['M']:.1f} kg (+ load), COM height {rows[0]['h']:.2f} m (lift mid, both arms straight out: the worst pose).", "",
         f"**Push to tip over, no load, 1.0 m high:** between wheels {rows0[0]['M'] * G * 0.21 * math.cos(math.radians(45)) / H_PUSH:.0f} N with wheels only, "
         f"{rows0[0]['M'] * G * min(0.21, CASTER_R) * math.cos(math.radians(22.5)) / H_PUSH:.0f} N with the casters (arms tucked, COM centred).", "",
         "| Load | Direction | Braking 0.5 m/s² | Nudge 30 N @ 1 m | COM offset (mm) | ZMP offset (mm) | Margin, wheels only (mm) | Margin, + D18 casters (mm) | |",
         "|---|---|---|---|---|---|---|---|---|"]
    L += [f"| {r['payload']:.1f} kg | {r['az']:.0f}° | {'yes' if r['brake'] else ''} | {'yes' if r['push'] else ''} | {r['com'] * 1000:.0f} | {r['zmp'] * 1000:.0f} | "
          f"{r0['margin'] * 1000:.0f} | {r['margin'] * 1000:.0f} | {'✅' if r['margin'] >= 0.03 else '❌'} |" for r0, r in zip(rows0, rows)]
    fails = [r for r in rows if r["margin"] < 0.03]
    L += ["", "**Reading (A10, loop 40):** the x-drive diamond is the weak point, not the mass: its edge is 148 mm from the centre between wheels. "
          "**D18:** four spring-loaded ball-transfer casters at the diagonals (≈ 5 N preload, hard stop after 5 mm, so they ride over thresholds) fill the diamond "
          "out to an octagon. **Planner rules** for what still fails: with a load over 1 kg, carry it close to the body (elbows bent) and pointing at a wheel "
          "(the base is holonomic: a turn costs nothing); cap braking with a load to 0.3 m/s²; slow to a crawl when a person is within reach (a firm shove at "
          "shoulder height can tip any 24 kg robot this narrow). "
          + ("Every case keeps ≥ 30 mm with the casters." if not fails else f"{len(fails)} of {len(rows)} worst-pose cases stay under 30 mm even with the casters; "
             "they are covered by the planner rules (no straight-arm carries with a load).")]
    (DOCS / "tip.md").write_text("\n".join(L))
    (DOCS / "tip.json").write_text(json.dumps({"worst": worst, "n_fail": len(fails), "n": len(rows)}))
    print("\n".join(L[4:]))


if __name__ == "__main__":
    main()
