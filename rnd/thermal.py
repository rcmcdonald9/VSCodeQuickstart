"""Motor thermal check: continuous task duty and worst-case hold times (confidence campaign).  python -m rnd.thermal

Model (per motor, first order). Copper loss scales with torque², so the steady winding rise is
ΔT_ss = ΔT_RATED · (τ / τ_rated)². τ_rated is the maker's continuous torque, taken to be the torque that gives ΔT_RATED
in still air (ESTIMATE). Heating follows ΔT(t) = ΔT_ss · (1 − e^(−t/TAU)).

Duty cases:
1. **Task day.** The MuJoCo fetch cycle repeated back to back with no rest, in the Monte Carlo worst corner: arms ×1.25,
   joint friction 0.6 N·m, motors at 75 % torque constant (so the same torque needs more current: τ_rated × 0.75), 0.6 kg can.
2. **Worst static hold.** The worst workspace pose with the 1 kg payload, held indefinitely. The result is the time to
   reach the limit.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

DOCS = Path(__file__).resolve().parent.parent / "docs" / "rnd"
AMBIENT, T_LIMIT = 30.0, 100.0      # °C: warm room; winding/driver limit (ESTIMATE: GIM/SDC104 class over-temp cut-out ~100 °C)
DT_RATED = 60.0                     # K rise at rated torque (ESTIMATE)
TAU = 600.0                         # s thermal time constant, 60–80 mm outrunner class (ESTIMATE)
WORST = dict(derate=0.75, mass=1.25, joint_friction=0.6, finger_mu=0.5, calib=np.zeros(6))


def rise(tau, rated):
    return DT_RATED * (tau / rated) ** 2


def hold_time(dt_ss):
    room = T_LIMIT - AMBIENT
    return math.inf if dt_ss <= room else -TAU * math.log(1 - room / dt_ss)


def main():
    from . import sim
    from .spring import workspace_margins
    L = sim.limits()
    r = sim.run(video=False, can_mass=0.6, perturb=WORST)
    rows, worst_task = [], 0.0
    for n, f in r["force"].items():
        if n == "a_fing_a_r":
            continue
        rated = L[n][0] * WORST["derate"]
        rms = math.sqrt(np.mean(np.square(f)))
        dt = rise(rms, rated)
        worst_task = max(worst_task, AMBIENT + dt)
        rows.append((n[2:].replace("_r", ""), rms, rated, AMBIENT + dt))
    hold = []
    for j, m in workspace_margins().items():
        dt = rise(m["max"], m["rated"])
        hold.append((j, m["max"], m["rated"], AMBIENT + dt, hold_time(dt)))
    L_ = ["# Motor thermal check (generated by `python -m rnd.thermal`)", "", __doc__.split("\n\n", 1)[1].strip(), "",
          f"Ambient {AMBIENT:.0f} °C, limit {T_LIMIT:.0f} °C, ΔT at rated {DT_RATED:.0f} K, τ {TAU:.0f} s (all ESTIMATE until the M1 bench arm logs a real motor's temperature).", "",
          "## 1. Task day: fetch cycle back to back, Monte Carlo worst corner", "",
          "| Actuator | RMS torque/force | Rated (derated ×0.75) | Steady temperature |", "|---|---|---|---|"]
    L_ += [f"| {n} | {rms:.2f} | {rt:.2f} | {T:.0f} °C {'✅' if T <= T_LIMIT else '❌'} |" for n, rms, rt, T in rows]
    L_ += ["", f"**Hottest motor on a non-stop task day: {worst_task:.0f} °C** (limit {T_LIMIT:.0f} °C).", "",
           "## 2. Worst static hold (worst workspace pose, 1 kg payload, nominal motors)", "",
           "| Joint | Worst static torque (N·m) | Rated (N·m) | Steady temperature | Time to the limit |", "|---|---|---|---|---|"]
    L_ += [f"| {j} | {mx:.1f} | {rt:.1f} | {T:.0f} °C | {'unlimited ✅' if math.isinf(t) else f'{t / 60:.0f} min'} |" for j, mx, rt, T, t in hold]
    lim = [t for *_, t in hold if not math.isinf(t)]
    L_ += ["", ("Every joint can hold its worst pose indefinitely." if not lim else
                f"**Some joints can't hold their worst pose forever (shortest {min(lim) / 60:.0f} min).** The planner must "
                "derate long holds at full reach (the driver's thermal model already does this). Normal reaching is far below the worst pose.")]
    (DOCS / "thermal.md").write_text("\n".join(L_))
    (DOCS / "thermal.json").write_text(json.dumps({"task_max_c": worst_task, "hold_min_s": min(lim) if lim else None}))
    print("\n".join(L_))


if __name__ == "__main__":
    main()
